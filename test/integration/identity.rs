/// Verifies: [DESIGN] RULES.md D63, D62 a checkpoint keeps the counter of a
/// sequence generator and of an identity column of its name, each of its
/// own epoch, though the other's is later: neither gives a value twice
/// after a crash. The rule keeping a counter is MC/DC of its two
/// conditions: S's counter is kept as its own epoch is published, though
/// T's identity generator of the name is of a later one; T's counter as
/// its own is, and no later one of the name is published; and the counter
/// of the generator ALTER restarted, of an earlier epoch, is not kept.
#[test]
fn a_sequence_and_an_identity_of_one_name_checkpointed() {
    let scratch = Scratch::new("identity-named");
    let (fs, dir): (Arc<dyn FileSystem>, _) = (Arc::new(OsFileSystem), scratch.path("db"));
    let before = opened(&fs, &dir);
    before.schema("CREATE SCHEMA AUTHORIZATION A CREATE SEQUENCE T START WITH 100 CREATE SEQUENCE R").unwrap();
    let a = before.session("A");
    a.run("CREATE TABLE T (K INTEGER GENERATED ALWAYS AS IDENTITY, V INTEGER)").unwrap();
    a.commit().unwrap();
    for _ in 0..3 {
        a.run("INSERT INTO T (V) VALUES (NEXT VALUE FOR T)").unwrap();
    }
    a.run("INSERT INTO T (V) VALUES (NEXT VALUE FOR R)").unwrap();
    a.commit().unwrap();
    a.run("ALTER SEQUENCE R RESTART WITH 50").unwrap();
    a.commit().unwrap();
    before.checkpoint().unwrap();
    let db = opened(&after_crash(), &dir);
    let a = db.session("A");
    a.run("INSERT INTO T (V) VALUES (NEXT VALUE FOR T)").unwrap();
    let last = query(&a, "SELECT MAX(K), MAX(V) FROM T WHERE V >= 100");
    let (k, v) = last[0].split_once(',').unwrap();
    assert!(k.parse::<i64>().unwrap() > 4 && v.parse::<i64>().unwrap() > 102, "K at {k}, V at {v}");
    assert_eq!(query(&a, "SELECT NEXT VALUE FOR R FROM (VALUES (0)) AS X (Z)"), ["50"]);
    a.rollback().unwrap();
    db.close().unwrap();
    drop((db, before));
}

/// The database in `dir`, opened from its files by `fs`.
fn opened(fs: &Arc<dyn FileSystem>, dir: &std::path::Path) -> Database {
    let db = Database::new();
    db.open_files(fs, dir, &OpenOptions::default()).unwrap();
    db
}

/// Verifies: [DESIGN] RULES.md D63, D62, D25 a database reopened, after a
/// close, a crash, or a crash after a checkpoint, never gives an identity
/// column a value it gave before, rolled back or not; a restart committed
/// goes on from its restart; a column added by a transaction the crash
/// ended is gone.
#[test]
fn never_given_again_after_reopening() {
    for (case, checkpoint, closed) in [("closed", false, true), ("crashed", false, false), ("checkpointed", true, false)] {
        let scratch = Scratch::new(&format!("identity-{case}"));
        let (fs, dir): (Arc<dyn FileSystem>, _) = (Arc::new(OsFileSystem), scratch.path("db"));
        let before = opened(&fs, &dir);
        before.schema("CREATE SCHEMA AUTHORIZATION A CREATE TABLE T (K INTEGER GENERATED ALWAYS AS IDENTITY, V INTEGER)").unwrap();
        before.schema("CREATE SCHEMA AUTHORIZATION B CREATE TABLE R (V INTEGER)").unwrap();
        let (a, b) = (before.session("A"), before.session("B"));
        for _ in 0..30 {
            a.run("INSERT INTO T (V) VALUES (0)").unwrap();
        }
        a.commit().unwrap();
        a.run("INSERT INTO T (V) VALUES (1)").unwrap();
        a.rollback().unwrap();
        b.run("INSERT INTO R VALUES (1), (2)").unwrap();
        b.run("ALTER TABLE R ADD COLUMN K INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 7)").unwrap();
        b.run("ALTER TABLE R ALTER COLUMN K RESTART WITH 70").unwrap();
        b.commit().unwrap();
        if checkpoint {
            before.checkpoint().unwrap();
        }
        a.run("INSERT INTO T (V) VALUES (2)").unwrap();
        a.commit().unwrap();
        b.run("INSERT INTO R (V) VALUES (3)").unwrap();
        b.commit().unwrap();
        b.run("ALTER TABLE R DROP COLUMN K CASCADE").unwrap();
        if closed {
            b.rollback().unwrap();
            before.close().unwrap();
        }
        let db = opened(&if closed { Arc::clone(&fs) } else { after_crash() }, &dir);
        let (a, b) = (db.session("A"), db.session("B"));
        a.run("INSERT INTO T (V) VALUES (3)").unwrap();
        let k: i64 = query(&a, "SELECT K FROM T WHERE V = 3")[0].parse().unwrap();
        assert!(k > 32, "{case}: T at {k}");
        assert_eq!(query(&b, "SELECT V, K FROM R ORDER BY V"), ["1,7", "2,8", "3,70"], "{case}");
        b.run("INSERT INTO R (V) VALUES (4)").unwrap();
        let r: i64 = query(&b, "SELECT K FROM R WHERE V = 4")[0].parse().unwrap();
        assert!(r > 70, "{case}: R at {r}");
        a.rollback().unwrap();
        b.rollback().unwrap();
        db.close().unwrap();
        drop((db, before));
    }
}
