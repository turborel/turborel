//! Identity columns [ISO/IEC 9075-2:2023 §4.17.12, §11.4, §11.20, §11.21;
//! RULES.md D63]: their definition, the values INSERT and UPDATE give them
//! by their sequence generator, with or without an `<override clause>`,
//! their alteration and drop, their description in the Information
//! Schema, and a value never given twice, by a rollback, a crash or a
//! checkpoint.

use std::sync::Arc;

use turborel::db::{Database, OpenOptions, Session};
use turborel::disk::io::{FileSystem, OsFileSystem};
use turborel::error::{Code, SqlError};

use crate::common::{Scratch, after_crash};

fn query(s: &Session, sql: &str) -> Vec<String> {
    let mut cursor = s.open_cursor(sql).unwrap();
    let mut out = Vec::new();
    while let Some(row) = cursor.fetch().unwrap() {
        out.push(row.iter().map(|v| v.to_string().trim_end().to_owned()).collect::<Vec<_>>().join(","));
    }
    out
}

/// The SQLCODE class of a refusal.
fn refused<T>(result: Result<T, SqlError>) -> Option<Code> {
    result.err().map(|e| e.code)
}

/// A database with schema A.
fn schema_a() -> Database {
    let db = Database::new();
    db.schema("CREATE SCHEMA AUTHORIZATION A").unwrap();
    db
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.4 SR16, GR4, §15.11 GR3a, §11.5
/// GR3a] an identity column of no options takes 1, 2, 3 in the rows that
/// give it no value, or DEFAULT; one of options starts and steps as they
/// say; and it is NOT NULL.
#[test]
fn values_drawn_11_4() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (K INTEGER GENERATED ALWAYS AS IDENTITY, V CHARACTER(1))").unwrap();
    a.run("CREATE TABLE U (K SMALLINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5), V CHARACTER(1))").unwrap();
    a.run("INSERT INTO T (V) VALUES ('a'), ('b')").unwrap();
    a.run("INSERT INTO T VALUES (DEFAULT, 'c')").unwrap();
    a.run("INSERT INTO T DEFAULT VALUES").unwrap();
    a.run("INSERT INTO U (V) VALUES ('a')").unwrap();
    a.run("INSERT INTO U VALUES (DEFAULT, 'b'), (7, 'c')").unwrap();
    assert_eq!(query(&a, "SELECT K, V FROM T ORDER BY K"), ["1,a", "2,b", "3,c", "4,NULL"]);
    assert_eq!(query(&a, "SELECT K, V FROM U ORDER BY V"), ["10,a", "15,b", "7,c"]);
    let nullable = "SELECT IS_NULLABLE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'K'";
    assert_eq!(query(&a, nullable), ["NO"], "SR16b");
    assert_eq!(refused(a.run("UPDATE U SET K = NULL")), Some(Code::Constraint), "NOT NULL NOT DEFERRABLE");
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.4 SR11, SR16a, §11.3 SR15, §11.11
/// SR3] an identity column has a data type, of an exact numeric type of
/// scale 0, and a table has at most one, as it is defined or a column is
/// added (SQLCODE -103).
#[test]
fn rules_of_definition_11_4() {
    let db = schema_a();
    let a = db.session("A");
    assert_eq!(refused(a.run("CREATE TABLE T (K GENERATED ALWAYS AS IDENTITY)")), Some(Code::SyntaxRule), "SR11");
    assert_eq!(refused(a.run("CREATE TABLE T (K DECIMAL(5,2) GENERATED ALWAYS AS IDENTITY)")), Some(Code::SyntaxRule), "scale 2");
    assert_eq!(refused(a.run("CREATE TABLE T (K REAL GENERATED ALWAYS AS IDENTITY)")), Some(Code::SyntaxRule), "approximate");
    let two = "CREATE TABLE T (K INTEGER GENERATED ALWAYS AS IDENTITY, J INTEGER GENERATED BY DEFAULT AS IDENTITY)";
    assert_eq!(refused(a.run(two)), Some(Code::SyntaxRule), "§11.3 SR15");
    a.run("CREATE TABLE T (K INTEGER GENERATED ALWAYS AS IDENTITY)").unwrap();
    assert_eq!(refused(a.run("ALTER TABLE T ADD COLUMN J INTEGER GENERATED ALWAYS AS IDENTITY")), Some(Code::SyntaxRule), "§11.11 SR3");
    let bounds = "CREATE TABLE U (K SMALLINT GENERATED ALWAYS AS IDENTITY (START WITH 700000))";
    assert_eq!(refused(a.run(bounds)), Some(Code::SyntaxRule), "§9.36 of the column's type");
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §14.11 SR13, GR7e] a value given an
/// identity column GENERATED ALWAYS is refused without an `<override
/// clause>`; OVERRIDING SYSTEM VALUE keeps the value given, OVERRIDING USER
/// VALUE ignores it; a column GENERATED BY DEFAULT takes OVERRIDING USER
/// VALUE alone; and no `<override clause>` is written without an identity
/// column given values (SQLCODE -103), nor with DEFAULT VALUES or a column
/// list before it (SQLCODE -104). Whether each row draws is MC/DC of its
/// three conditions, the identity column is no object column, OVERRIDING
/// USER VALUE, DEFAULT VALUES: `T (V)` and `U VALUES (5, 4)` show the
/// first, `OVERRIDING USER VALUE` and `U VALUES (5, 4)` the second, `T
/// DEFAULT VALUES` (in `values_drawn_11_4`) and `U VALUES (5, 4)` the
/// third. A row of DEFAULT under OVERRIDING USER VALUE draws once.
#[test]
fn override_clause_14_11() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (K INTEGER GENERATED ALWAYS AS IDENTITY, V INTEGER)").unwrap();
    a.run("CREATE TABLE U (K INTEGER GENERATED BY DEFAULT AS IDENTITY, V INTEGER)").unwrap();
    a.run("CREATE TABLE P (V INTEGER)").unwrap();
    let syntax = [
        "INSERT INTO T (V) DEFAULT VALUES",
        "INSERT INTO T OVERRIDING USER VALUE DEFAULT VALUES",
        "INSERT INTO T OVERRIDING VALUE VALUES (1, 1)",
    ];
    for sql in syntax {
        assert_eq!(refused(a.run(sql)), Some(Code::Syntax), "{sql}");
    }
    assert_eq!(refused(a.run("INSERT INTO T VALUES (5, 0)")), Some(Code::SyntaxRule), "SR13b");
    assert_eq!(refused(a.run("INSERT INTO T SELECT V, V FROM P")), Some(Code::SyntaxRule), "SR13b of a query");
    a.run("INSERT INTO T OVERRIDING SYSTEM VALUE VALUES (50, 1)").unwrap();
    a.run("INSERT INTO T OVERRIDING USER VALUE VALUES (60, 2), (DEFAULT, 3)").unwrap();
    a.run("INSERT INTO T (V) VALUES (4)").unwrap();
    assert_eq!(query(&a, "SELECT V, K FROM T ORDER BY V"), ["1,50", "2,1", "3,2", "4,3"], "one value a row");
    assert_eq!(refused(a.run("INSERT INTO U OVERRIDING SYSTEM VALUE VALUES (5, 0)")), Some(Code::SyntaxRule), "SR13c");
    a.run("INSERT INTO U OVERRIDING USER VALUE VALUES (5, 3)").unwrap();
    a.run("INSERT INTO U VALUES (5, 4)").unwrap();
    assert_eq!(query(&a, "SELECT K, V FROM U ORDER BY V"), ["1,3", "5,4"]);
    assert_eq!(refused(a.run("INSERT INTO P OVERRIDING USER VALUE VALUES (1)")), Some(Code::SyntaxRule), "no identity column");
    let defaulted = "INSERT INTO T (V) OVERRIDING SYSTEM VALUE VALUES (1)";
    assert_eq!(refused(a.run(defaulted)), Some(Code::SyntaxRule), "SR13 none given");
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §14.15 SR5, §15.14 GR7a] an identity column
/// GENERATED ALWAYS is set only to DEFAULT, which gives each row its
/// generator's next value; one GENERATED BY DEFAULT takes a value too.
#[test]
fn updated_14_15() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (K INTEGER GENERATED ALWAYS AS IDENTITY, V INTEGER)").unwrap();
    a.run("CREATE TABLE U (K INTEGER GENERATED BY DEFAULT AS IDENTITY, V INTEGER)").unwrap();
    a.run("INSERT INTO T (V) VALUES (1), (2)").unwrap();
    a.run("INSERT INTO U (V) VALUES (1)").unwrap();
    assert_eq!(refused(a.run("UPDATE T SET K = 9")), Some(Code::SyntaxRule), "SR5");
    assert_eq!(refused(a.run("UPDATE T SET K = NULL")), Some(Code::SyntaxRule), "SR5 of NULL");
    a.run("UPDATE T SET K = DEFAULT").unwrap();
    assert_eq!(query(&a, "SELECT K, V FROM T ORDER BY V"), ["3,1", "4,2"]);
    a.run("UPDATE U SET K = 9").unwrap();
    a.run("UPDATE U SET V = V + 1").unwrap();
    assert_eq!(query(&a, "SELECT K, V FROM U"), ["9,2"]);
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.20 GR1 to GR3, §11.21, §11.12 SR6,
/// SR7, §9.37] ALTER COLUMN changes an identity column's generation and
/// options, an increment going on from the generator's current base value,
/// restarts it, at its start or a value given, drops its identity, after
/// which it takes a value of its own and keeps its NOT NULL; SET or DROP
/// DEFAULT of an identity column, or an identity action of another, is
/// refused (SQLCODE -103), as are an action of no option and SET START or
/// SET RESTART (SQLCODE -104). SR6's two conditions are MC/DC: SET DEFAULT
/// of K refused, RESTART of K and SET DEFAULT of K once it is no identity
/// column taken.
#[test]
fn altered_11_20() {
    let db = schema_a();
    let a = db.session("A");
    let syntax = [
        "ALTER TABLE T ALTER COLUMN K",
        "ALTER TABLE T ALTER COLUMN K SET START WITH 1",
        "ALTER TABLE T ALTER COLUMN K SET RESTART",
        "ALTER TABLE T ALTER COLUMN K SET NO RESTART",
        "ALTER TABLE T ALTER COLUMN K SET GENERATED",
    ];
    a.run("CREATE TABLE T (K INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 5), V INTEGER)").unwrap();
    a.run("INSERT INTO T (V) VALUES (1), (2)").unwrap();
    for sql in syntax {
        assert_eq!(refused(a.run(sql)), Some(Code::Syntax), "{sql}");
    }
    a.run("ALTER TABLE T ALTER COLUMN K SET GENERATED BY DEFAULT SET INCREMENT BY 10").unwrap();
    a.run("INSERT INTO T VALUES (100, 3)").unwrap();
    a.run("INSERT INTO T (V) VALUES (4)").unwrap();
    a.run("ALTER TABLE T ALTER COLUMN K RESTART").unwrap();
    a.run("INSERT INTO T (V) VALUES (5)").unwrap();
    a.run("ALTER TABLE T ALTER COLUMN K RESTART WITH 1000").unwrap();
    a.run("INSERT INTO T (V) VALUES (6)").unwrap();
    assert_eq!(query(&a, "SELECT V, K FROM T ORDER BY V"), ["1,5", "2,6", "3,100", "4,7", "5,5", "6,1000"]);
    assert_eq!(refused(a.run("ALTER TABLE T ALTER COLUMN K SET DEFAULT 1")), Some(Code::SyntaxRule), "SR6");
    assert_eq!(refused(a.run("ALTER TABLE T ALTER COLUMN K DROP DEFAULT")), Some(Code::SyntaxRule), "SR6");
    assert_eq!(refused(a.run("ALTER TABLE T ALTER COLUMN V RESTART")), Some(Code::SyntaxRule), "SR7");
    assert_eq!(refused(a.run("ALTER TABLE T ALTER COLUMN V DROP IDENTITY")), Some(Code::SyntaxRule), "SR7");
    let bounds = "ALTER TABLE T ALTER COLUMN K SET MAXVALUE 10";
    assert_eq!(refused(a.run(bounds)), Some(Code::SyntaxRule), "§9.37 of a restart value past it");
    a.run("ALTER TABLE T ALTER COLUMN K DROP IDENTITY").unwrap();
    assert_eq!(refused(a.run("INSERT INTO T (V) VALUES (7)")), Some(Code::Constraint), "NOT NULL stays");
    a.run("INSERT INTO T VALUES (7, 7)").unwrap();
    a.run("ALTER TABLE T ALTER COLUMN K SET DEFAULT 0").unwrap();
    let described = "SELECT IS_IDENTITY, IDENTITY_GENERATION FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'K'";
    assert_eq!(query(&a, described), ["NO,NULL"]);
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.11 GR2b, §11.23] an identity column
/// added to a table of rows gives each its generator's next value, and
/// another column added after it leaves its generator where it was; the
/// column dropped takes its generator with it, and one added anew starts
/// again. Giving an epoch is MC/DC of its two conditions: the identity
/// column added is given one, the identity column there when X is added
/// keeps its own, and a column of no identity none.
#[test]
fn added_and_dropped_11_11() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (V INTEGER)").unwrap();
    a.run("INSERT INTO T VALUES (1), (2), (3)").unwrap();
    a.run("ALTER TABLE T ADD COLUMN K INTEGER GENERATED ALWAYS AS IDENTITY").unwrap();
    assert_eq!(query(&a, "SELECT COUNT(DISTINCT K), MIN(K), MAX(K) FROM T"), ["3,1,3"]);
    a.run("INSERT INTO T (V) VALUES (4)").unwrap();
    a.run("ALTER TABLE T ADD COLUMN X INTEGER").unwrap();
    a.run("INSERT INTO T (V) VALUES (5)").unwrap();
    assert_eq!(query(&a, "SELECT V, K FROM T WHERE V > 3 ORDER BY V"), ["4,4", "5,5"]);
    a.run("ALTER TABLE T DROP COLUMN K RESTRICT").unwrap();
    a.run("ALTER TABLE T ADD COLUMN K INTEGER GENERATED ALWAYS AS IDENTITY").unwrap();
    assert_eq!(query(&a, "SELECT MAX(K) FROM T"), ["5"]);
    a.commit().unwrap();
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §9.35 GR3a] an identity column whose
