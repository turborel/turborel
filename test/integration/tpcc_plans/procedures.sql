-- The five TPC-C transactions as procedures, as the HammerDB driver
-- defines them, one after another.

CREATE PROCEDURE NEWORD (
    IN NO_W_ID INTEGER,
    IN NO_D_ID INTEGER,
    IN NO_C_ID INTEGER,
    IN NO_O_OL_CNT INTEGER,
    IN NO_O_ALL_LOCAL SMALLINT,
    IN NO_ITEMS INTEGER ARRAY[15],
    IN NO_SUPPLY INTEGER ARRAY[15],
    IN NO_QUANTITY INTEGER ARRAY[15])
    MODIFIES SQL DATA
    BEGIN
    DECLARE NO_C_DISCOUNT DECIMAL(4,4);
    DECLARE NO_C_LAST VARCHAR(16);
    DECLARE NO_C_CREDIT CHAR(2);
    DECLARE NO_W_TAX DECIMAL(4,4);
    DECLARE NO_D_TAX DECIMAL(4,4);
    DECLARE NO_O_ID INTEGER;
    DECLARE LOOP_COUNTER INTEGER DEFAULT 1;
    DECLARE NO_S_DIST CHAR(24);
    DECLARE NO_S_DISTS CHAR(24) ARRAY[15] DEFAULT ARRAY[];
    SELECT C_DISCOUNT, C_LAST, C_CREDIT, W_TAX
        INTO NO_C_DISCOUNT, NO_C_LAST, NO_C_CREDIT, NO_W_TAX
        FROM CUSTOMER, WAREHOUSE
        WHERE W_ID = NO_W_ID AND C_W_ID = NO_W_ID AND C_D_ID = NO_D_ID AND C_ID = NO_C_ID;
    SELECT D_NEXT_O_ID - 1, D_TAX INTO NO_O_ID, NO_D_TAX
        FROM FINAL TABLE (UPDATE DISTRICT SET D_NEXT_O_ID = D_NEXT_O_ID + 1
            WHERE D_ID = NO_D_ID AND D_W_ID = NO_W_ID);
    INSERT INTO ORDERS (O_ID, O_D_ID, O_W_ID, O_C_ID, O_ENTRY_D, O_OL_CNT, O_ALL_LOCAL)
        VALUES (NO_O_ID, NO_D_ID, NO_W_ID, NO_C_ID, CAST(CURRENT_TIMESTAMP(0) AS TIMESTAMP(0)), NO_O_OL_CNT, NO_O_ALL_LOCAL);
    INSERT INTO NEW_ORDER (NO_O_ID, NO_D_ID, NO_W_ID) VALUES (NO_O_ID, NO_D_ID, NO_W_ID);
    WHILE LOOP_COUNTER <= NO_O_OL_CNT DO
        SET NO_S_DIST = NULL;
        SELECT CASE NO_D_ID WHEN 1 THEN S_DIST_01 WHEN 2 THEN S_DIST_02 WHEN 3 THEN S_DIST_03
                WHEN 4 THEN S_DIST_04 WHEN 5 THEN S_DIST_05 WHEN 6 THEN S_DIST_06
                WHEN 7 THEN S_DIST_07 WHEN 8 THEN S_DIST_08 WHEN 9 THEN S_DIST_09
                ELSE S_DIST_10 END
            INTO NO_S_DIST
            FROM FINAL TABLE (UPDATE STOCK SET S_QUANTITY =
                CASE WHEN S_QUANTITY < NO_QUANTITY[LOOP_COUNTER] + 10 THEN S_QUANTITY + 91 ELSE S_QUANTITY END
                    - NO_QUANTITY[LOOP_COUNTER]
                WHERE S_I_ID = NO_ITEMS[LOOP_COUNTER] AND S_W_ID = NO_SUPPLY[LOOP_COUNTER]);
        SET NO_S_DISTS = NO_S_DISTS || ARRAY[NO_S_DIST];
        SET LOOP_COUNTER = LOOP_COUNTER + 1;
    END WHILE;
    INSERT INTO ORDER_LINE (OL_O_ID, OL_D_ID, OL_W_ID, OL_NUMBER, OL_I_ID,
        OL_SUPPLY_W_ID, OL_QUANTITY, OL_AMOUNT, OL_DIST_INFO)
        SELECT NO_O_ID, NO_D_ID, NO_W_ID, L.N, L.L_I_ID, L.L_W_ID, L.L_QUANTITY,
            L.L_QUANTITY * (SELECT I_PRICE FROM ITEM WHERE I_ID = L.L_I_ID)
                * (1 + NO_W_TAX + NO_D_TAX) * (1 - NO_C_DISCOUNT),
            L.L_DIST
        FROM UNNEST(NO_ITEMS, NO_SUPPLY, NO_QUANTITY, NO_S_DISTS) WITH ORDINALITY
            AS L (L_I_ID, L_W_ID, L_QUANTITY, L_DIST, N);
    END

CREATE PROCEDURE PAYMENT (
    IN P_W_ID INTEGER,
    IN P_D_ID INTEGER,
    IN P_C_W_ID INTEGER,
    IN P_C_D_ID INTEGER,
    IN P_C_ID INTEGER,
    IN BYNAME INTEGER,
    IN P_H_AMOUNT DECIMAL(6,2),
    IN P_C_LAST VARCHAR(16))
    MODIFIES SQL DATA
    BEGIN
    DECLARE C_ID_V INTEGER;
    DECLARE NAMECNT INTEGER;
    DECLARE LOOP_COUNTER INTEGER;
    DECLARE W_STREET_1_V VARCHAR(20);
    DECLARE W_STREET_2_V VARCHAR(20);
    DECLARE W_CITY_V VARCHAR(20);
    DECLARE W_STATE_V CHAR(2);
    DECLARE W_ZIP_V CHAR(9);
    DECLARE W_NAME_V VARCHAR(10);
    DECLARE D_STREET_1_V VARCHAR(20);
    DECLARE D_STREET_2_V VARCHAR(20);
    DECLARE D_CITY_V VARCHAR(20);
    DECLARE D_STATE_V CHAR(2);
    DECLARE D_ZIP_V CHAR(9);
    DECLARE D_NAME_V VARCHAR(10);
    DECLARE C_FIRST_V VARCHAR(16);
    DECLARE C_MIDDLE_V CHAR(2);
    DECLARE C_LAST_V VARCHAR(16);
    DECLARE C_STREET_1_V VARCHAR(20);
    DECLARE C_STREET_2_V VARCHAR(20);
    DECLARE C_CITY_V VARCHAR(20);
    DECLARE C_STATE_V CHAR(2);
    DECLARE C_ZIP_V CHAR(9);
    DECLARE C_PHONE_V CHAR(16);
    DECLARE C_SINCE_V TIMESTAMP;
    DECLARE C_CREDIT_V CHAR(2) DEFAULT '0';
    DECLARE C_CREDIT_LIM_V DECIMAL(12,2);
    DECLARE C_DISCOUNT_V DECIMAL(4,4);
    DECLARE C_BALANCE_V DECIMAL(12,2) DEFAULT 0;
    DECLARE C_DATA_V VARCHAR(500);
    DECLARE C_BYNAME CURSOR FOR
        SELECT C_FIRST, C_MIDDLE, C_ID, C_STREET_1, C_STREET_2, C_CITY, C_STATE, C_ZIP,
            C_PHONE, C_CREDIT, C_CREDIT_LIM, C_DISCOUNT, C_BALANCE, C_SINCE
        FROM CUSTOMER
        WHERE C_W_ID = P_C_W_ID AND C_D_ID = P_C_D_ID AND C_LAST = P_C_LAST
        ORDER BY C_FIRST;
    SET C_ID_V = P_C_ID;
    SET C_LAST_V = P_C_LAST;
    SELECT W_STREET_1, W_STREET_2, W_CITY, W_STATE, W_ZIP, W_NAME
        INTO W_STREET_1_V, W_STREET_2_V, W_CITY_V, W_STATE_V, W_ZIP_V, W_NAME_V
        FROM FINAL TABLE (UPDATE WAREHOUSE SET W_YTD = W_YTD + P_H_AMOUNT WHERE W_ID = P_W_ID);
    SELECT D_STREET_1, D_STREET_2, D_CITY, D_STATE, D_ZIP, D_NAME
        INTO D_STREET_1_V, D_STREET_2_V, D_CITY_V, D_STATE_V, D_ZIP_V, D_NAME_V
        FROM FINAL TABLE (UPDATE DISTRICT SET D_YTD = D_YTD + P_H_AMOUNT
            WHERE D_W_ID = P_W_ID AND D_ID = P_D_ID);
    IF BYNAME = 1 THEN
        SELECT COUNT(C_LAST) INTO NAMECNT FROM CUSTOMER
            WHERE C_LAST = P_C_LAST AND C_D_ID = P_C_D_ID AND C_W_ID = P_C_W_ID;
        SET NAMECNT = FLOOR(NAMECNT / 2);
        OPEN C_BYNAME;
        SET LOOP_COUNTER = 0;
        WHILE LOOP_COUNTER < NAMECNT DO
            FETCH C_BYNAME INTO C_FIRST_V, C_MIDDLE_V, C_ID_V, C_STREET_1_V, C_STREET_2_V,
                C_CITY_V, C_STATE_V, C_ZIP_V, C_PHONE_V, C_CREDIT_V, C_CREDIT_LIM_V,
                C_DISCOUNT_V, C_BALANCE_V, C_SINCE_V;
            SET LOOP_COUNTER = LOOP_COUNTER + 1;
        END WHILE;
        CLOSE C_BYNAME;
    ELSE
        SELECT C_FIRST, C_MIDDLE, C_LAST, C_STREET_1, C_STREET_2, C_CITY, C_STATE, C_ZIP,
            C_PHONE, C_CREDIT, C_CREDIT_LIM, C_DISCOUNT, C_BALANCE, C_SINCE
            INTO C_FIRST_V, C_MIDDLE_V, C_LAST_V, C_STREET_1_V, C_STREET_2_V, C_CITY_V,
            C_STATE_V, C_ZIP_V, C_PHONE_V, C_CREDIT_V, C_CREDIT_LIM_V, C_DISCOUNT_V,
            C_BALANCE_V, C_SINCE_V
            FROM CUSTOMER WHERE C_W_ID = P_C_W_ID AND C_D_ID = P_C_D_ID AND C_ID = C_ID_V;
    END IF;
    IF C_CREDIT_V = 'BC' THEN
        SELECT C_BALANCE, C_DATA INTO C_BALANCE_V, C_DATA_V
            FROM FINAL TABLE (UPDATE CUSTOMER SET C_BALANCE = C_BALANCE_V - P_H_AMOUNT,
                C_DATA = SUBSTRING(CAST(C_ID_V AS VARCHAR(10)) || ' ' || CAST(P_C_D_ID AS VARCHAR(10))
                    || ' ' || CAST(P_C_W_ID AS VARCHAR(10)) || ' ' || CAST(P_D_ID AS VARCHAR(10))
                    || ' ' || CAST(P_W_ID AS VARCHAR(10)) || ' ' || CAST(P_H_AMOUNT AS VARCHAR(10))
                    || ' | ' || C_DATA FROM 1 FOR 500)
                WHERE C_W_ID = P_C_W_ID AND C_D_ID = P_C_D_ID AND C_ID = C_ID_V);
    ELSE
        SELECT C_BALANCE INTO C_BALANCE_V
            FROM FINAL TABLE (UPDATE CUSTOMER SET C_BALANCE = C_BALANCE_V - P_H_AMOUNT
                WHERE C_W_ID = P_C_W_ID AND C_D_ID = P_C_D_ID AND C_ID = C_ID_V);
    END IF;
    INSERT INTO HISTORY (H_C_D_ID, H_C_W_ID, H_C_ID, H_D_ID, H_W_ID, H_DATE, H_AMOUNT, H_DATA)
        VALUES (P_C_D_ID, P_C_W_ID, C_ID_V, P_D_ID, P_W_ID, CAST(CURRENT_TIMESTAMP(0) AS TIMESTAMP(0)),
            P_H_AMOUNT, W_NAME_V || ' ' || D_NAME_V);
    END

CREATE PROCEDURE DELIVERY (
    IN D_W_ID INTEGER,
    IN D_O_CARRIER_ID INTEGER)
    MODIFIES SQL DATA
    BEGIN
    DECLARE D_D_ID INTEGER DEFAULT 1;
    DECLARE D_NO_O_ID INTEGER;
    DECLARE D_DELETED INTEGER;
    DECLARE D_C_ID INTEGER;
    DECLARE D_OL_TOTAL DECIMAL(12,2);
    WHILE D_D_ID <= 10 DO
        SET D_NO_O_ID = NULL;
        SET D_DELETED = NULL;
        SELECT MIN(NO_O_ID) INTO D_NO_O_ID FROM NEW_ORDER
            WHERE NO_W_ID = D_W_ID AND NO_D_ID = D_D_ID;
        IF D_NO_O_ID IS NOT NULL THEN
            SELECT NO_O_ID INTO D_DELETED FROM OLD TABLE (DELETE FROM NEW_ORDER
                WHERE NO_W_ID = D_W_ID AND NO_D_ID = D_D_ID AND NO_O_ID = D_NO_O_ID);
        END IF;
        IF D_DELETED IS NOT NULL THEN
            SELECT O_C_ID INTO D_C_ID FROM FINAL TABLE (UPDATE ORDERS SET O_CARRIER_ID = D_O_CARRIER_ID
                WHERE O_ID = D_NO_O_ID AND O_D_ID = D_D_ID AND O_W_ID = D_W_ID);
            SELECT SUM(OL_AMOUNT) INTO D_OL_TOTAL FROM FINAL TABLE (UPDATE ORDER_LINE
                SET OL_DELIVERY_D = CAST(CURRENT_TIMESTAMP(0) AS TIMESTAMP(0))
                WHERE OL_O_ID = D_NO_O_ID AND OL_D_ID = D_D_ID AND OL_W_ID = D_W_ID);
            UPDATE CUSTOMER SET C_BALANCE = COALESCE(C_BALANCE, 0) + D_OL_TOTAL
                WHERE C_ID = D_C_ID AND C_D_ID = D_D_ID AND C_W_ID = D_W_ID;
        END IF;
        SET D_D_ID = D_D_ID + 1;
    END WHILE;
    END

CREATE PROCEDURE OSTAT (
    IN OS_W_ID INTEGER,
    IN OS_D_ID INTEGER,
    IN OS_C_ID INTEGER,
    IN BYNAME INTEGER,
    IN OS_C_LAST VARCHAR(16))
    READS SQL DATA
    BEGIN
    DECLARE C_ID_V INTEGER;
    DECLARE NAMECNT INTEGER;
    DECLARE LOOP_COUNTER INTEGER;
    DECLARE C_FIRST_V VARCHAR(16);
    DECLARE C_MIDDLE_V CHAR(2);
    DECLARE C_LAST_V VARCHAR(16);
    DECLARE C_BALANCE_V DECIMAL(12,2);
    DECLARE O_ID_V INTEGER;
    DECLARE O_CARRIER_ID_V SMALLINT;
    DECLARE O_ENTRY_D_V TIMESTAMP;
    DECLARE LINES_V INTEGER DEFAULT 0;
    DECLARE AMOUNT_V DECIMAL(12,2) DEFAULT 0;
    DECLARE C_NAME CURSOR FOR
        SELECT C_BALANCE, C_FIRST, C_MIDDLE, C_ID
        FROM CUSTOMER
        WHERE C_LAST = OS_C_LAST AND C_D_ID = OS_D_ID AND C_W_ID = OS_W_ID
        ORDER BY C_FIRST;
    SET C_ID_V = OS_C_ID;
    IF BYNAME = 1 THEN
        SELECT COUNT(C_ID) INTO NAMECNT FROM CUSTOMER
            WHERE C_LAST = OS_C_LAST AND C_D_ID = OS_D_ID AND C_W_ID = OS_W_ID;
        SET NAMECNT = LEAST(FLOOR((NAMECNT + MOD(NAMECNT, 2)) / 2) + 1, NAMECNT);
        OPEN C_NAME;
        SET LOOP_COUNTER = 0;
        WHILE LOOP_COUNTER < NAMECNT DO
            FETCH C_NAME INTO C_BALANCE_V, C_FIRST_V, C_MIDDLE_V, C_ID_V;
            SET LOOP_COUNTER = LOOP_COUNTER + 1;
        END WHILE;
        CLOSE C_NAME;
        SET C_LAST_V = OS_C_LAST;
    ELSE
        SELECT C_BALANCE, C_FIRST, C_MIDDLE, C_LAST
            INTO C_BALANCE_V, C_FIRST_V, C_MIDDLE_V, C_LAST_V
            FROM CUSTOMER WHERE C_ID = C_ID_V AND C_D_ID = OS_D_ID AND C_W_ID = OS_W_ID;
    END IF;
    SELECT O_ID, O_CARRIER_ID, O_ENTRY_D INTO O_ID_V, O_CARRIER_ID_V, O_ENTRY_D_V
        FROM (SELECT O_ID, O_CARRIER_ID, O_ENTRY_D FROM ORDERS
            WHERE O_D_ID = OS_D_ID AND O_W_ID = OS_W_ID AND O_C_ID = C_ID_V
            ORDER BY O_ID DESC FETCH FIRST 1 ROW ONLY) AS LAST_ORDER;
    FOR OL AS SELECT OL_I_ID, OL_SUPPLY_W_ID, OL_QUANTITY, OL_AMOUNT, OL_DELIVERY_D
        FROM ORDER_LINE
        WHERE OL_O_ID = O_ID_V AND OL_D_ID = OS_D_ID AND OL_W_ID = OS_W_ID DO
        SET LINES_V = LINES_V + 1;
        SET AMOUNT_V = AMOUNT_V + OL_AMOUNT;
    END FOR;
    END

CREATE PROCEDURE SLEV (
    IN ST_W_ID INTEGER,
    IN ST_D_ID INTEGER,
    IN THRESHOLD INTEGER)
    READS SQL DATA
    BEGIN
    DECLARE ST_O_ID INTEGER;
    DECLARE STOCK_COUNT INTEGER;
    SELECT D_NEXT_O_ID INTO ST_O_ID FROM DISTRICT
        WHERE D_W_ID = ST_W_ID AND D_ID = ST_D_ID;
    SELECT COUNT(DISTINCT S_I_ID) INTO STOCK_COUNT
        FROM ORDER_LINE, STOCK
        WHERE OL_W_ID = ST_W_ID AND OL_D_ID = ST_D_ID
        AND OL_O_ID < ST_O_ID AND OL_O_ID >= ST_O_ID - 20
        AND S_W_ID = ST_W_ID AND S_I_ID = OL_I_ID AND S_QUANTITY < THRESHOLD;
    END
