//! Generated columns [ISO/IEC 9075-2:2023 §4.17.13, §11.4, §11.22, §11.23;
//! RULES.md D63]: their definition and the rules of their generation
//! expressions, the values INSERT, UPDATE and referential actions give
//! them, their drop and the drop of a column they reference, DROP
//! EXPRESSION, and their description in the Information Schema.

use std::sync::Arc;

use turborel::db::{Database, OpenOptions, Session};
use turborel::disk::io::{FileSystem, OsFileSystem};
use turborel::error::{Code, SqlError};

use crate::common::{Scratch, after_crash};

fn query(s: &Session, sql: &str) -> Vec<String> {
    let mut cursor = s.open_cursor(sql).unwrap();
    let mut out = Vec::new();
    while let Some(row) = cursor.fetch().unwrap() {
        out.push(row.iter().map(|v| v.to_string().trim_end().to_owned()).collect::<Vec<_>>().join(","));
    }
    out
}

/// The SQLCODE class of a refusal.
fn refused<T>(result: Result<T, SqlError>) -> Option<Code> {
    result.err().map(|e| e.code)
}

/// A database with schema A.
fn schema_a() -> Database {
    let db = Database::new();
    db.schema("CREATE SCHEMA AUTHORIZATION A").unwrap();
    db
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.4 SR13, §15.11 GR6a, §15.14 GR9] a
/// generated column takes its expression's value of each row inserted and
/// each row updated; of no data type written, its expression's type.
#[test]
fn values_computed_15_11() {
    let db = schema_a();
    let a = db.session("A");
    a.run(
        "CREATE TABLE T (A INTEGER, B INTEGER, S GENERATED ALWAYS AS (A + B), L VARCHAR(10) GENERATED ALWAYS AS (UPPER(N)), N VARCHAR(10))",
    )
    .unwrap();
    a.run("INSERT INTO T (A, B, N) VALUES (1, 2, 'x'), (10, NULL, 'y')").unwrap();
    a.run("INSERT INTO T VALUES (5, 5, DEFAULT, DEFAULT, 'z')").unwrap();
    assert_eq!(query(&a, "SELECT A, S, L FROM T ORDER BY A"), ["1,3,X", "5,10,Z", "10,NULL,Y"]);
    a.run("UPDATE T SET B = 0 WHERE A = 10").unwrap();
    a.run("UPDATE T SET N = 'q', S = DEFAULT WHERE A = 1").unwrap();
    assert_eq!(query(&a, "SELECT A, S, L FROM T ORDER BY A"), ["1,3,Q", "5,10,Z", "10,10,Y"]);
    let typed = "SELECT DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'S'";
    assert_eq!(query(&a, typed), ["NUMERIC"], "SR13c, as A + B is");
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.4 SR10, SR11, SR13] a generation
/// expression references only base columns of its table, none generated,
/// contains no query expression, no set function and no potential source of
/// non-determinism, and is of a type assignable to its column; a column
/// with neither a type nor a generation is refused (SQLCODE -103, or -104
/// for a syntax error).
#[test]
fn rules_of_definition_11_4() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE P (K INTEGER)").unwrap();
    let cases = [
        ("CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS (Z + 1))", "no such column"),
        ("CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS (A), H INTEGER GENERATED ALWAYS AS (G))", "SR10c"),
        ("CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS ((SELECT MAX(K) FROM P)))", "SR10f"),
        ("CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS (SUM(A)))", "set function"),
        ("CREATE TABLE T (A INTEGER, G TIMESTAMP GENERATED ALWAYS AS (CURRENT_TIMESTAMP))", "SR10d"),
        ("CREATE TABLE T (A INTEGER, G VARCHAR(5) GENERATED ALWAYS AS (USER))", "SR10d of USER"),
        ("CREATE TABLE T (A INTEGER, G DATE GENERATED ALWAYS AS (A + 1))", "SR13a"),
    ];
    for (sql, why) in cases {
        assert_eq!(refused(a.run(sql)), Some(Code::SyntaxRule), "{why}");
    }
    let syntax = [
        ("CREATE TABLE T (A INTEGER, G)", "SR11"),
        ("CREATE TABLE T (A INTEGER DEFAULT 1 GENERATED ALWAYS AS (2))", "a default or a generation"),
        ("CREATE TABLE T (A INTEGER, G INTEGER GENERATED BY DEFAULT AS (A))", "only ALWAYS"),
    ];
    for (sql, why) in syntax {
        assert_eq!(refused(a.run(sql)), Some(Code::Syntax), "{why}");
    }
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §5.2, §11.4] GENERATED, ALWAYS and
/// EXPRESSION are non-reserved words: a domain named GENERATED is a
/// column's type, as GENERATED is followed by neither ALWAYS nor BY. MC/DC
/// of the three conditions of a generation's start: GENERATED ALWAYS and
/// GENERATED BY begin one, GENERATED alone and ALWAYS alone do not.
#[test]
fn non_reserved_words() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE DOMAIN GENERATED AS INTEGER").unwrap();
    a.run("CREATE TABLE ALWAYS (A GENERATED, B GENERATED DEFAULT 3, EXPRESSION INTEGER, G GENERATED ALWAYS AS (A + 1))").unwrap();
    a.run("CREATE TABLE U (K INTEGER GENERATED BY DEFAULT AS IDENTITY, ALWAYS INTEGER)").unwrap();
    a.run("INSERT INTO ALWAYS (A, EXPRESSION) VALUES (1, 2)").unwrap();
    assert_eq!(query(&a, "SELECT * FROM ALWAYS"), ["1,3,2,2"]);
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §14.11 SR12, §14.15 SR5] an INSERT gives a
/// generated column only DEFAULT, in every row, and an UPDATE sets it only
/// to DEFAULT (SQLCODE -103).
#[test]
fn given_only_default_14_11() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS (A * 2))").unwrap();
    a.run("CREATE TABLE P (A INTEGER, B INTEGER)").unwrap();
    assert_eq!(refused(a.run("INSERT INTO T VALUES (1, 2)")), Some(Code::SyntaxRule), "SR12");
    assert_eq!(refused(a.run("INSERT INTO T VALUES (1, DEFAULT), (2, 4)")), Some(Code::SyntaxRule), "SR12 in one row");
    assert_eq!(refused(a.run("INSERT INTO T SELECT A, B FROM P")), Some(Code::SyntaxRule), "SR12 of a query");
    assert_eq!(refused(a.run("INSERT INTO T OVERRIDING SYSTEM VALUE VALUES (1, 2)")), Some(Code::SyntaxRule), "no override");
    a.run("INSERT INTO T (A) VALUES (4)").unwrap();
    assert_eq!(refused(a.run("UPDATE T SET G = 1")), Some(Code::SyntaxRule), "SR5");
    assert_eq!(query(&a, "SELECT G FROM T"), ["8"]);
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.11 GR2a, §11.22, §11.12 SR8, SR9] a
/// generated column added to a table of rows is computed for each; DROP
/// EXPRESSION leaves its values, after which it takes values of its own;
/// SET DEFAULT of a generated column, or DROP EXPRESSION of another, is
/// refused (SQLCODE -103).
#[test]
fn added_and_expression_dropped_11_22() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (A INTEGER)").unwrap();
    a.run("INSERT INTO T VALUES (1), (2)").unwrap();
    a.run("ALTER TABLE T ADD COLUMN G INTEGER GENERATED ALWAYS AS (A * 10)").unwrap();
    assert_eq!(query(&a, "SELECT A, G FROM T ORDER BY A"), ["1,10", "2,20"]);
    assert_eq!(refused(a.run("ALTER TABLE T ALTER COLUMN G SET DEFAULT 0")), Some(Code::SyntaxRule), "SR9");
    assert_eq!(refused(a.run("ALTER TABLE T ALTER COLUMN A DROP EXPRESSION")), Some(Code::SyntaxRule), "SR8");
    a.run("ALTER TABLE T ALTER COLUMN G DROP EXPRESSION").unwrap();
    a.run("INSERT INTO T VALUES (3, 7)").unwrap();
    a.run("UPDATE T SET A = A + 1").unwrap();
    assert_eq!(query(&a, "SELECT A, G FROM T ORDER BY A"), ["2,10", "3,20", "4,7"]);
    let described =
        "SELECT IS_GENERATED, GENERATION_EXPRESSION FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'G'";
    assert_eq!(query(&a, described), ["NEVER,NULL"]);
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.23 SR7f, GR3] a column a generation
/// expression references is dropped only with CASCADE, which drops the
/// generated column first; a generated column itself drops alone. If the
/// drop fails once its generated columns are dropped, the transaction only
/// rolls back (SQLCODE -913 at its commit); if it fails before, it goes on.
/// MC/DC of that decision's two conditions: the drop of the only column
/// left, A of U, after G went, dooms; the drop of V's only column, none
/// gone before, does not; the drop of A of T, after G and with B left,
/// succeeds.
#[test]
fn referenced_column_dropped_11_23() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (A INTEGER, B INTEGER, G INTEGER GENERATED ALWAYS AS (A + B), H INTEGER GENERATED ALWAYS AS (B))").unwrap();
    a.run("INSERT INTO T (A, B) VALUES (1, 2)").unwrap();
    assert_eq!(refused(a.run("ALTER TABLE T DROP COLUMN A RESTRICT")), Some(Code::SyntaxRule), "SR7f");
    a.run("ALTER TABLE T DROP COLUMN H RESTRICT").unwrap();
    a.run("ALTER TABLE T DROP COLUMN A CASCADE").unwrap();
    assert_eq!(query(&a, "SELECT * FROM T"), ["2"]);
    a.commit().unwrap();
    let left = "SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T'";
    assert_eq!(query(&a, left), ["B"]);
    a.run("CREATE TABLE U (A INTEGER, G INTEGER GENERATED ALWAYS AS (A))").unwrap();
    a.run("CREATE TABLE V (A INTEGER)").unwrap();
    a.commit().unwrap();
    assert_eq!(refused(a.run("ALTER TABLE V DROP COLUMN A CASCADE")), Some(Code::SyntaxRule), "the only column");
    a.run("INSERT INTO V VALUES (1)").unwrap();
    a.commit().unwrap();
    assert_eq!(refused(a.run("ALTER TABLE U DROP COLUMN A CASCADE")), Some(Code::SyntaxRule), "the only column, G gone");
    assert_eq!(refused(a.commit()), Some(Code::CommitFailed), "doomed");
    assert_eq!(query(&a, "SELECT COUNT(*) FROM V"), ["1"]);
    let kept = "SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'U' ORDER BY COLUMN_NAME";
    assert_eq!(query(&a, kept), ["A", "G"]);
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.8 SR14, §15.14 GR9] a foreign key of a
/// generated referencing column neither sets it null nor to its default,
/// nor cascades an update to it (SQLCODE -103); a referential action that
/// changes a column a generated column references computes it anew.
#[test]
fn referential_actions_11_8() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE P (K INTEGER PRIMARY KEY)").unwrap();
    let cases = [
        ("CREATE TABLE C (A INTEGER, G INTEGER GENERATED ALWAYS AS (A) REFERENCES P ON DELETE SET NULL)", "SR14a"),
        ("CREATE TABLE C (A INTEGER, G INTEGER GENERATED ALWAYS AS (A) REFERENCES P ON UPDATE SET DEFAULT)", "SR14a"),
        ("CREATE TABLE C (A INTEGER, G INTEGER GENERATED ALWAYS AS (A) REFERENCES P ON UPDATE CASCADE)", "SR14b"),
    ];
    for (sql, why) in cases {
        assert_eq!(refused(a.run(sql)), Some(Code::SyntaxRule), "{why}");
    }
    a.run("CREATE TABLE C (A INTEGER REFERENCES P ON UPDATE CASCADE, G INTEGER GENERATED ALWAYS AS (A * 100))").unwrap();
    a.run("CREATE TABLE D (A INTEGER, G INTEGER GENERATED ALWAYS AS (A) REFERENCES P ON DELETE CASCADE)").unwrap();
    a.run("INSERT INTO P VALUES (1), (2)").unwrap();
    a.run("INSERT INTO C (A) VALUES (1)").unwrap();
    a.run("INSERT INTO D (A) VALUES (2)").unwrap();
    a.run("UPDATE P SET K = 3 WHERE K = 1").unwrap();
    assert_eq!(query(&a, "SELECT A, G FROM C"), ["3,300"]);
    a.run("DELETE FROM P WHERE K = 2").unwrap();
    assert_eq!(query(&a, "SELECT COUNT(*) FROM D"), ["0"]);
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §15.11 GR6a] a generated column under a
/// UNIQUE constraint or a CHECK is checked as any column; an expression
/// that raises refuses the row.
#[test]
fn constrained_and_raising() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS (A / 2) UNIQUE CHECK (G < 10))").unwrap();
    a.run("INSERT INTO T (A) VALUES (2)").unwrap();
    assert_eq!(refused(a.run("INSERT INTO T (A) VALUES (3)")), Some(Code::Constraint), "unique");
    assert_eq!(refused(a.run("INSERT INTO T (A) VALUES (40)")), Some(Code::Constraint), "check");
    assert_eq!(refused(a.run("UPDATE T SET A = 50")), Some(Code::Constraint), "check on update");
    a.run("CREATE TABLE U (A INTEGER, G INTEGER GENERATED ALWAYS AS (10 / A))").unwrap();
    let e = a.run("INSERT INTO U (A) VALUES (0)").err().unwrap();
    assert_eq!(e.sqlstate().as_str(), "22012");
}

/// Verifies: [EXTENSION] the Information Schema's COLUMNS describes a
/// generated column, ALWAYS and its expression as written; its
/// COLUMN_DEFAULT is null.
#[test]
fn described_in_columns() {
    let db = schema_a();
    let a = db.session("A");
    a.run("CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS ( A  *  2 ))").unwrap();
    let described = "SELECT COLUMN_DEFAULT, IS_IDENTITY, IS_GENERATED, GENERATION_EXPRESSION FROM INFORMATION_SCHEMA.COLUMNS
                     WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'G'";
    assert_eq!(query(&a, described), ["NULL,NO,ALWAYS,A  *  2"]);
}

/// Verifies: [EXTENSION] [ISO/IEC 9075-2:2023 §11.4 SR10b] a generation expression's
/// names are resolved in its table's schema, whatever schema the statement
/// that writes the table is run in; a view's INSERT computes its base
/// table's generated columns.
#[test]
fn bound_in_its_schema() {
    let db = schema_a();
    db.schema("CREATE SCHEMA AUTHORIZATION B").unwrap();
    let a = db.session("A");
    a.run("CREATE DOMAIN D AS INTEGER").unwrap();
    a.run("CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS (CAST (A AS D) + 1))").unwrap();
    a.run("CREATE VIEW V AS SELECT A FROM T").unwrap();
    a.run("GRANT INSERT, SELECT ON T TO B").unwrap();
    a.run("INSERT INTO V VALUES (1)").unwrap();
    a.commit().unwrap();
    let b = db.session("B");
    b.run("INSERT INTO A.T (A) VALUES (5)").unwrap();
    assert_eq!(query(&b, "SELECT A, G FROM A.T ORDER BY A"), ["1,2", "5,6"]);
}

/// The database in `dir`, opened from its files by `fs`.
fn opened(fs: &Arc<dyn FileSystem>, dir: &std::path::Path) -> Database {
    let db = Database::new();
    db.open_files(fs, dir, &OpenOptions::default()).unwrap();
    db
}

/// Verifies: [DESIGN] RULES.md D63, D25 a generated column's definition
/// and stored values, and DROP EXPRESSION and the cascaded drop of one,
/// survive a close, a crash, and a crash after a checkpoint.
#[test]
fn recovered() {
    for (case, checkpoint, closed) in [("closed", false, true), ("crashed", false, false), ("checkpointed", true, false)] {
        let scratch = Scratch::new(&format!("generated-{case}"));
        let (fs, dir): (Arc<dyn FileSystem>, _) = (Arc::new(OsFileSystem), scratch.path("db"));
        let before = opened(&fs, &dir);
        before
            .schema("CREATE SCHEMA AUTHORIZATION A CREATE TABLE T (A INTEGER, G INTEGER GENERATED ALWAYS AS (A + 1), B INTEGER)")
            .unwrap();
        let a = before.session("A");
        a.run("INSERT INTO T (A, B) VALUES (1, 1)").unwrap();
        a.run("ALTER TABLE T ADD COLUMN H GENERATED ALWAYS AS (B * 2)").unwrap();
        a.run("ALTER TABLE T ADD COLUMN I GENERATED ALWAYS AS (B * 3)").unwrap();
        a.commit().unwrap();
        if checkpoint {
            before.checkpoint().unwrap();
        }
        a.run("ALTER TABLE T ALTER COLUMN H DROP EXPRESSION").unwrap();
        a.run("ALTER TABLE T DROP COLUMN B CASCADE").unwrap();
        a.commit().unwrap();
        if closed {
            before.close().unwrap();
        }
        let db = opened(&if closed { Arc::clone(&fs) } else { after_crash() }, &dir);
        let a = db.session("A");
        assert_eq!(query(&a, "SELECT * FROM T"), ["1,2,2"], "{case}");
        a.run("INSERT INTO T (A, H) VALUES (5, 0)").unwrap();
        assert_eq!(query(&a, "SELECT A, G, H FROM T ORDER BY A"), ["1,2,2", "5,6,0"], "{case}");
        a.rollback().unwrap();
        db.close().unwrap();
        drop((db, before));
    }
}
