//! Identity columns and generated columns [ISO/IEC 9075-2:2023 §11.4,
//! §11.12, §11.20 to §11.22, §14.11]: the `<identity column
//! specification>` and `<generation clause>` of a column definition, the
//! `<alter column action>`s, and an INSERT's `<override clause>`.
//! GENERATED, ALWAYS, EXPRESSION and OVERRIDING are `<non-reserved word>`s
//! [§5.2], identifiers elsewhere. SYSTEM is a `<reserved word>` of SQL:2023
//! but not of SQL-92, so it stays an identifier elsewhere too, as a schema
//! of SQL-92 may use it.

use super::Parser;
use crate::ast::{AlterColumnAction, ColumnGeneration, Overriding, SequenceOptions, ValueExpression};
use crate::error::Result;
use crate::lexer::{Tok, delim, kw};

/// The `<non-reserved word>` a generation begins with.
const GENERATED: &str = "GENERATED";
/// The `<non-reserved word>` of values always generated.
const ALWAYS: &str = "ALWAYS";
/// The `<non-reserved word>` DROP EXPRESSION drops.
const EXPRESSION: &str = "EXPRESSION";
/// The `<non-reserved word>` an `<override clause>` begins with.
const OVERRIDING: &str = "OVERRIDING";
/// The word of OVERRIDING SYSTEM VALUE, which only SQL:2023 reserves.
const SYSTEM: &str = "SYSTEM";
/// The `<non-reserved word>` of an `<alter sequence generator restart
/// option>`, and of RESTART IDENTITY.
pub(super) const RESTART: &str = "RESTART";
/// The `<non-reserved word>` of START WITH, no `<basic sequence generator
/// option>`.
const START: &str = "START";

impl Parser {
    /// Whether GENERATED ALWAYS or GENERATED BY is next: a generation, not
    /// a domain of the name GENERATED.
    pub(super) fn at_generation(&self) -> bool {
        let generated = matches!(self.peek(), Tok::Identifier(w) if w == GENERATED);
        let then = matches!(self.peek_at(1), Tok::Identifier(w) if w == ALWAYS) || self.next_is_kw(kw::BY);
        generated && then
    }

    /// [ISO/IEC 9075-2:2023 §11.4] An `<identity column specification>` or
    /// a `<generation clause>`, if one is next.
    ///
    /// # Errors
    ///
    /// What follows GENERATED is neither.
    pub(super) fn column_generation(&mut self) -> Result<Option<ColumnGeneration>> {
        if !self.at_generation() {
            return Ok(None);
        }
        let at = self.here();
        self.advance();
        let always = self.accept_word(ALWAYS);
        if !always {
            self.expect_kw(kw::BY)?;
            self.expect_kw(kw::DEFAULT)?;
        }
        self.expect_kw(kw::AS)?;
        // <generation clause> ::= GENERATED ALWAYS AS ( <value expression> )
        if always && self.accept_delim(delim::LEFT_PAREN) {
            let start = self.here();
            let value = self.value_expression()?;
            let text = self.text_from(start);
            self.expect_delim(delim::RIGHT_PAREN)?;
            return Ok(Some(ColumnGeneration::Expression { value, text, at }));
        }
        // ... AS IDENTITY [ ( <common sequence generator options> ) ]
        self.expect_kw(kw::IDENTITY)?;
        let mut options = SequenceOptions::default();
        if self.accept_delim(delim::LEFT_PAREN) {
            if !self.sequence_option(&mut options, false)? {
                return Err(self.syntax("expected a <common sequence generator option>"));
            }
            while self.sequence_option(&mut options, false)? {}
            self.expect_delim(delim::RIGHT_PAREN)?;
        }
        Ok(Some(ColumnGeneration::Identity { always, options, at }))
    }

    /// [ISO/IEC 9075-2:2023 §11.4] A generation expression, alone, as the
    /// column descriptor keeps it.
    ///
    /// # Errors
    ///
    /// The text is not a `<value expression>`.
    pub fn generation_expression(&mut self) -> Result<ValueExpression> {
        let value = self.value_expression()?;
        self.end()?;
        Ok(value)
    }

    /// [ISO/IEC 9075-2:2023 §11.12] An `<alter column action>`, after
    /// ALTER \[COLUMN\] `<column name>`.
    ///
    /// # Errors
    ///
    /// The text is not one of those implemented.
    pub(super) fn alter_column_action(&mut self) -> Result<AlterColumnAction> {
        if self.accept_kw(kw::DROP) {
            if self.accept_kw(kw::DEFAULT) {
                return Ok(AlterColumnAction::DropDefault);
            }
            // [§11.21] DROP IDENTITY; [§11.22] DROP EXPRESSION.
            if self.accept_kw(kw::IDENTITY) {
                return Ok(AlterColumnAction::DropIdentity);
            }
            if self.accept_word(EXPRESSION) {
                return Ok(AlterColumnAction::DropExpression);
            }
            return Err(self.syntax("expected DEFAULT, IDENTITY or EXPRESSION"));
        }
        if self.is_kw(kw::SET) && self.next_is_kw(kw::DEFAULT) {
            self.advance();
            self.advance();
            return Ok(AlterColumnAction::SetDefault(self.default_option()?));
        }
        // [§11.20] <set identity column generation clause> ::= SET GENERATED
        // { ALWAYS | BY DEFAULT }
        let mut always = None;
        if self.is_kw(kw::SET) && matches!(self.peek_at(1), Tok::Identifier(w) if w == GENERATED) {
            self.advance();
            self.advance();
            always = Some(self.accept_word(ALWAYS));
            if always == Some(false) {
                self.expect_kw(kw::BY)?;
                self.expect_kw(kw::DEFAULT)?;
            }
        }
        let mut options = SequenceOptions::default();
        let mut any = false;
        while self.identity_option(&mut options)? {
            any = true;
        }
        if always.is_none() && !any {
            return Err(self
                .syntax("expected SET DEFAULT, DROP DEFAULT, an <alter identity column specification>, DROP IDENTITY or DROP EXPRESSION"));
        }
        Ok(AlterColumnAction::Identity { always, options: Box::new(options) })
    }

    /// [ISO/IEC 9075-2:2023 §11.20] An `<alter identity column option>`, if
    /// one is next, added to `options`: RESTART, or SET and a `<basic
    /// sequence generator option>`. Whether one was.
    fn identity_option(&mut self, options: &mut SequenceOptions) -> Result<bool> {
        if matches!(self.peek(), Tok::Identifier(w) if w == RESTART) {
            return self.sequence_option(options, true);
        }
        if !self.is_kw(kw::SET) {
            return Ok(false);
        }
        let after = if self.next_is_kw(kw::NO) { 2 } else { 1 };
        if matches!(self.peek_at(after), Tok::Identifier(w) if w == RESTART || w == START) {
            return Err(self.syntax("expected a <basic sequence generator option>"));
        }
        self.advance();
        if !self.sequence_option(options, true)? {
            return Err(self.syntax("expected a <basic sequence generator option>"));
        }
        Ok(true)
    }

    /// [ISO/IEC 9075-2:2023 §14.11] `<override clause>` ::= OVERRIDING USER
    /// VALUE | OVERRIDING SYSTEM VALUE, if written.
    ///
    /// # Errors
    ///
    /// OVERRIDING is not followed by USER VALUE or SYSTEM VALUE.
    pub(super) fn override_clause(&mut self) -> Result<Option<Overriding>> {
        if !self.accept_word(OVERRIDING) {
            return Ok(None);
        }
        let overriding = if self.accept_kw(kw::USER) {
            Overriding::User
        } else if self.accept_word(SYSTEM) {
            Overriding::System
        } else {
            return Err(self.syntax("expected USER or SYSTEM"));
        };
        self.expect_kw(kw::VALUE)?;
        Ok(Some(overriding))
    }
}
