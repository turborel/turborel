//! The views of the Information Schema of structured types, reference
//! types and typed tables [ISO/IEC 9075-11:2006 draft §5.11, §5.25,
//! §5.26, §5.33, §5.34, §5.36, §5.59]. Each reads its table of the
//! Definition Schema (`definition/structured.rs`, `definition/typed.rs`,
//! `definition/descriptors.rs`), whose rows hold the columns of the data
//! type descriptor they name, so each reads them there rather than joined
//! from DATA_TYPE_DESCRIPTOR, and each finds a descriptor's character set
//! from its collation, as the views of user-defined types do
//! (`information/user_types.rs`). Each correction to the draft's text is
//! noted; INTERVAL_TYPE and INTERVAL_PRECISION are not shown, as no view
//! of this implementation shows them, nor the columns of a `<result cast>`
//! or a timestamp, which no SQL-invoked method has.
//!
//! The privileges on a type are read from DEFINITION_SCHEMA.UDT_PRIVILEGES,
//! whose columns UDT_PRIVILEGES reads, in place of the draft's
//! USER_DEFINED_TYPE_PRIVILEGES.

use super::SystemView;

/// The views, after those of user-defined types.
pub(super) const VIEWS: &[SystemView] = &[
    // [§5.11] ATTRIBUTES.
    SystemView {
        name: "ATTRIBUTES",
        query: r"SELECT DISTINCT
       A.UDT_CATALOG, A.UDT_SCHEMA, A.UDT_NAME,
       A.ATTRIBUTE_NAME, A.ORDINAL_POSITION, A.ATTRIBUTE_DEFAULT,
       A.DATA_TYPE, A.CHARACTER_MAXIMUM_LENGTH, A.CHARACTER_OCTET_LENGTH,
       S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
       A.COLLATION_CATALOG, A.COLLATION_SCHEMA, A.COLLATION_NAME,
       A.NUMERIC_PRECISION, A.NUMERIC_PRECISION_RADIX, A.NUMERIC_SCALE,
       A.DATETIME_PRECISION,
       A.USER_DEFINED_TYPE_CATALOG AS ATTRIBUTE_UDT_CATALOG,
       A.USER_DEFINED_TYPE_SCHEMA AS ATTRIBUTE_UDT_SCHEMA,
       A.USER_DEFINED_TYPE_NAME AS ATTRIBUTE_UDT_NAME,
       A.SCOPE_CATALOG, A.SCOPE_SCHEMA, A.SCOPE_NAME,
       A.MAXIMUM_CARDINALITY, A.DTD_IDENTIFIER, A.IS_DERIVED_REFERENCE_ATTRIBUTE
     FROM DEFINITION_SCHEMA.ATTRIBUTES AS A
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( A.COLLATION_CATALOG, A.COLLATION_SCHEMA, A.COLLATION_NAME ) )
     WHERE ( A.UDT_CATALOG, A.UDT_SCHEMA, A.UDT_NAME ) IN
           ( SELECT UDTP.UDT_CATALOG, UDTP.UDT_SCHEMA, UDTP.UDT_NAME
             FROM DEFINITION_SCHEMA.UDT_PRIVILEGES AS UDTP
             WHERE ( UDTP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                     OR UDTP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND A.UDT_CATALOG
         = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [§5.25] DIRECT_SUPERTABLES, as the draft writes it.
    SystemView {
        name: "DIRECT_SUPERTABLES",
        query: r"SELECT DS.TABLE_CATALOG, DS.TABLE_SCHEMA, DS.TABLE_NAME, DS.SUPERTABLE_NAME
     FROM DEFINITION_SCHEMA.DIRECT_SUPERTABLES AS DS
       JOIN
           DEFINITION_SCHEMA.SCHEMATA AS S
         ON ( ( DS.TABLE_CATALOG, DS.TABLE_SCHEMA )
             = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
     WHERE ( S.SCHEMA_OWNER = CURRENT_USER
            OR
               S.SCHEMA_OWNER IN
               ( SELECT ER.ROLE_NAME
                 FROM ENABLED_ROLES AS ER ) )
       AND
           DS.TABLE_CATALOG
        = ( SELECT ISCN.CATALOG_NAME
             FROM INFORMATION_SCHEMA_CATALOG_NAME AS ISCN )",
    },
    // [§5.26] DIRECT_SUPERTYPES.
    SystemView {
        name: "DIRECT_SUPERTYPES",
        query: r"SELECT USER_DEFINED_TYPE_CATALOG AS UDT_CATALOG,
            USER_DEFINED_TYPE_SCHEMA AS UDT_SCHEMA,
            USER_DEFINED_TYPE_NAME AS UDT_NAME,
            SUPERTYPE_CATALOG, SUPERTYPE_SCHEMA, SUPERTYPE_NAME
     FROM DEFINITION_SCHEMA.DIRECT_SUPERTYPES
     WHERE ( USER_DEFINED_TYPE_CATALOG, USER_DEFINED_TYPE_SCHEMA,
             USER_DEFINED_TYPE_NAME ) IN
             ( SELECT UDTP.UDT_CATALOG, UDTP.UDT_SCHEMA, UDTP.UDT_NAME
               FROM DEFINITION_SCHEMA.UDT_PRIVILEGES AS UDTP
                 JOIN
                    DEFINITION_SCHEMA.SCHEMATA AS S
                 ON ( ( UDTP.UDT_CATALOG, UDTP.UDT_SCHEMA )
                    = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
               WHERE ( S.SCHEMA_OWNER = CURRENT_USER
                     OR S.SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND USER_DEFINED_TYPE_CATALOG
         = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [§5.34] METHOD_SPECIFICATIONS; corrected: the method's type read from
    // the columns UDT_CATALOG, UDT_SCHEMA and UDT_NAME, its result type's
    // name being those of its descriptor.
    SystemView {
        name: "METHOD_SPECIFICATIONS",
        query: r"SELECT M.SPECIFIC_CATALOG, M.SPECIFIC_SCHEMA, M.SPECIFIC_NAME,
            M.UDT_CATALOG, M.UDT_SCHEMA, M.UDT_NAME,
            M.METHOD_NAME, M.IS_STATIC, M.IS_OVERRIDING, M.IS_CONSTRUCTOR,
            M.DATA_TYPE, M.CHARACTER_MAXIMUM_LENGTH, M.CHARACTER_OCTET_LENGTH,
            S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
            M.COLLATION_CATALOG, M.COLLATION_SCHEMA, M.COLLATION_NAME,
            M.NUMERIC_PRECISION, M.NUMERIC_PRECISION_RADIX, M.NUMERIC_SCALE,
            M.DATETIME_PRECISION,
            M.USER_DEFINED_TYPE_CATALOG AS RETURN_UDT_CATALOG,
            M.USER_DEFINED_TYPE_SCHEMA AS RETURN_UDT_SCHEMA,
            M.USER_DEFINED_TYPE_NAME AS RETURN_UDT_NAME,
            M.SCOPE_CATALOG, M.SCOPE_SCHEMA, M.SCOPE_NAME,
            M.MAXIMUM_CARDINALITY, M.DTD_IDENTIFIER, M.METHOD_LANGUAGE,
            M.PARAMETER_STYLE, M.IS_DETERMINISTIC, M.SQL_DATA_ACCESS,
            M.IS_NULL_CALL,
            M.TO_SQL_SPECIFIC_CATALOG, M.TO_SQL_SPECIFIC_SCHEMA,
            M.TO_SQL_SPECIFIC_NAME, M.AS_LOCATOR
     FROM DEFINITION_SCHEMA.METHOD_SPECIFICATIONS AS M
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( M.COLLATION_CATALOG, M.COLLATION_SCHEMA, M.COLLATION_NAME ) )
     WHERE ( M.UDT_CATALOG, M.UDT_SCHEMA, M.UDT_NAME ) IN
           ( SELECT UDTP.UDT_CATALOG, UDTP.UDT_SCHEMA, UDTP.UDT_NAME
             FROM DEFINITION_SCHEMA.UDT_PRIVILEGES AS UDTP
             WHERE ( UDTP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                     OR UDTP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND M.UDT_CATALOG
         = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [§5.33] METHOD_SPECIFICATION_PARAMETERS; corrected: the method's type
    // read from METHOD_SPECIFICATIONS as above, joined ON its specific
    // name, as the draft's USING would.
    SystemView {
        name: "METHOD_SPECIFICATION_PARAMETERS",
        query: r"SELECT P.SPECIFIC_CATALOG, P.SPECIFIC_SCHEMA, P.SPECIFIC_NAME,
            P.ORDINAL_POSITION, P.PARAMETER_MODE, P.IS_RESULT,
            P.AS_LOCATOR, P.PARAMETER_NAME,
            P.FROM_SQL_SPECIFIC_CATALOG, P.FROM_SQL_SPECIFIC_SCHEMA,
            P.FROM_SQL_SPECIFIC_NAME, P.DATA_TYPE,
            P.CHARACTER_MAXIMUM_LENGTH, P.CHARACTER_OCTET_LENGTH,
            S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
            P.COLLATION_CATALOG, P.COLLATION_SCHEMA, P.COLLATION_NAME,
            P.NUMERIC_PRECISION, P.NUMERIC_PRECISION_RADIX, P.NUMERIC_SCALE,
            P.DATETIME_PRECISION,
            P.USER_DEFINED_TYPE_CATALOG AS PARAMETER_UDT_CATALOG,
            P.USER_DEFINED_TYPE_SCHEMA AS PARAMETER_UDT_SCHEMA,
            P.USER_DEFINED_TYPE_NAME AS PARAMETER_UDT_NAME,
            P.SCOPE_CATALOG, P.SCOPE_SCHEMA, P.SCOPE_NAME,
            P.MAXIMUM_CARDINALITY, P.DTD_IDENTIFIER
     FROM DEFINITION_SCHEMA.METHOD_SPECIFICATION_PARAMETERS AS P
         JOIN
           DEFINITION_SCHEMA.METHOD_SPECIFICATIONS AS M
           ON ( ( P.SPECIFIC_CATALOG, P.SPECIFIC_SCHEMA, P.SPECIFIC_NAME )
              = ( M.SPECIFIC_CATALOG, M.SPECIFIC_SCHEMA, M.SPECIFIC_NAME ) )
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( P.COLLATION_CATALOG, P.COLLATION_SCHEMA, P.COLLATION_NAME ) )
     WHERE ( M.UDT_CATALOG, M.UDT_SCHEMA, M.UDT_NAME ) IN
           ( SELECT UDTP.UDT_CATALOG, UDTP.UDT_SCHEMA, UDTP.UDT_NAME
             FROM DEFINITION_SCHEMA.UDT_PRIVILEGES AS UDTP
             WHERE ( UDTP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                     OR UDTP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND M.UDT_CATALOG
         = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [§5.36] REFERENCED_TYPES; corrected: of the objects the current user
    // is shown, as ELEMENT_TYPES chooses them (`information/composites.rs`),
    // there being no view DATA_TYPE_PRIVILEGES.
    SystemView {
        name: "REFERENCED_TYPES",
        query: r"SELECT DISTINCT
         R.OBJECT_CATALOG, R.OBJECT_SCHEMA, R.OBJECT_NAME,
         R.OBJECT_TYPE, R.REFERENCE_TYPE_IDENTIFIER, R.DATA_TYPE,
         R.CHARACTER_MAXIMUM_LENGTH, R.CHARACTER_OCTET_LENGTH,
         S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
         R.COLLATION_CATALOG, R.COLLATION_SCHEMA, R.COLLATION_NAME,
         R.NUMERIC_PRECISION, R.NUMERIC_PRECISION_RADIX, R.NUMERIC_SCALE,
         R.DATETIME_PRECISION,
         R.USER_DEFINED_TYPE_CATALOG AS UDT_CATALOG,
         R.USER_DEFINED_TYPE_SCHEMA AS UDT_SCHEMA,
         R.USER_DEFINED_TYPE_NAME AS UDT_NAME,
         R.SCOPE_CATALOG, R.SCOPE_SCHEMA, R.SCOPE_NAME,
         R.MAXIMUM_CARDINALITY, R.DTD_IDENTIFIER
     FROM DEFINITION_SCHEMA.REFERENCED_TYPES AS R
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( R.COLLATION_CATALOG, R.COLLATION_SCHEMA, R.COLLATION_NAME ) )
     WHERE ( ( R.OBJECT_TYPE = 'TABLE'
               AND ( R.OBJECT_CATALOG, R.OBJECT_SCHEMA, R.OBJECT_NAME )
                 IN ( SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                        FROM TABLES ) )
             OR
             ( R.OBJECT_TYPE = 'DOMAIN'
               AND ( R.OBJECT_CATALOG, R.OBJECT_SCHEMA, R.OBJECT_NAME )
                 IN ( SELECT DOMAIN_CATALOG, DOMAIN_SCHEMA, DOMAIN_NAME
                        FROM DOMAINS ) )
             OR
             ( R.OBJECT_TYPE = 'USER-DEFINED TYPE'
               AND ( R.OBJECT_CATALOG, R.OBJECT_SCHEMA, R.OBJECT_NAME )
                 IN ( SELECT USER_DEFINED_TYPE_CATALOG,
                             USER_DEFINED_TYPE_SCHEMA, USER_DEFINED_TYPE_NAME
                        FROM USER_DEFINED_TYPES
                      UNION
                      SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME
                        FROM METHOD_SPECIFICATIONS ) )
             OR
             ( R.OBJECT_TYPE = 'ROUTINE'
               AND ( R.OBJECT_CATALOG, R.OBJECT_SCHEMA, R.OBJECT_NAME )
                 IN ( SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME
                        FROM ROUTINES ) ) )
       AND R.OBJECT_CATALOG
         = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [§5.59] TABLE_METHOD_PRIVILEGES, as the draft writes it.
    SystemView {
        name: "TABLE_METHOD_PRIVILEGES",
        query: r"SELECT GRANTOR, GRANTEE, TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
             SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME, IS_GRANTABLE
     FROM DEFINITION_SCHEMA.TABLE_METHOD_PRIVILEGES
     WHERE ( GRANTEE IN
              ( 'PUBLIC', CURRENT_USER )
          OR
              GRANTEE IN
              ( SELECT ROLE_NAME
                FROM ENABLED_ROLES )
          OR
              GRANTOR
           = CURRENT_USER
          OR
              GRANTOR IN
              ( SELECT ROLE_NAME
                FROM ENABLED_ROLES ) )
       AND
           TABLE_CATALOG
         = ( SELECT CATALOG_NAME
              FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
];
