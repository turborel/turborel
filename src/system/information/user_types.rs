//! The views of the Information Schema of user-defined types and their
//! routines, as ISO/IEC 9075-11 names them. USER_DEFINED_TYPES shows each
//! distinct type and UDT_PRIVILEGES each privilege on one. ROUTINES,
//! PARAMETERS and ROUTINE_PRIVILEGES show the functions each type's
//! definition makes [ISO/IEC 9075-2:2023 §11.51 GR2], and TRANSFORMS each
//! type's transform group. Each reads its table of the Definition Schema
//! (`definition/user_types.rs`). Their text is this implementation's, as
//! ISO/IEC 9075:1992 has none of them.
//!
//! A type is shown to the current user if it or PUBLIC holds a privilege
//! on it, as DOMAINS shows domains [ISO/IEC 9075:1992 §21.2.5], and a
//! function likewise. A privilege is shown to its grantee and its grantor,
//! as TABLE_PRIVILEGES shows one [§21.2.10]. Each view shows a data type
//! descriptor's character set, which the descriptor's collation is of, and
//! the columns ISO/IEC 9075-11 names for a user-defined type's name.

use super::SystemView;

/// The views, after those of arrays and row types.
pub(super) const VIEWS: &[SystemView] = &[
    SystemView {
        name: "USER_DEFINED_TYPES",
        query: r"SELECT
       U.USER_DEFINED_TYPE_CATALOG, U.USER_DEFINED_TYPE_SCHEMA,
       U.USER_DEFINED_TYPE_NAME, U.USER_DEFINED_TYPE_CATEGORY,
       U.IS_INSTANTIABLE, U.IS_FINAL, U.ORDERING_FORM, U.ORDERING_CATEGORY,
       U.ORDERING_ROUTINE_CATALOG, U.ORDERING_ROUTINE_SCHEMA,
       U.ORDERING_ROUTINE_NAME, U.REFERENCE_TYPE, U.DATA_TYPE,
       U.CHARACTER_MAXIMUM_LENGTH, U.CHARACTER_OCTET_LENGTH,
       S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
       U.COLLATION_CATALOG, U.COLLATION_SCHEMA, U.COLLATION_NAME,
       U.NUMERIC_PRECISION, U.NUMERIC_PRECISION_RADIX, U.NUMERIC_SCALE,
       U.DATETIME_PRECISION, U.MAXIMUM_CARDINALITY,
       U.SOURCE_DTD_IDENTIFIER, U.REF_DTD_IDENTIFIER
     FROM DEFINITION_SCHEMA.USER_DEFINED_TYPES AS U
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( U.COLLATION_CATALOG, U.COLLATION_SCHEMA, U.COLLATION_NAME ) )
         WHERE ( U.USER_DEFINED_TYPE_CATALOG, U.USER_DEFINED_TYPE_SCHEMA,
                 U.USER_DEFINED_TYPE_NAME )
             IN ( SELECT UDT_CATALOG, UDT_SCHEMA, UDT_NAME
                    FROM DEFINITION_SCHEMA.UDT_PRIVILEGES
                    WHERE GRANTEE IN ( 'PUBLIC', CURRENT_USER ) )
         AND U.USER_DEFINED_TYPE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    SystemView {
        name: "UDT_PRIVILEGES",
        query: r"SELECT
       GRANTOR, GRANTEE, UDT_CATALOG, UDT_SCHEMA, UDT_NAME,
         PRIVILEGE_TYPE, IS_GRANTABLE
     FROM DEFINITION_SCHEMA.UDT_PRIVILEGES
         WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                 OR GRANTOR = CURRENT_USER )
         AND UDT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    SystemView {
        name: "ROUTINES",
        query: r"SELECT
       R.SPECIFIC_CATALOG, R.SPECIFIC_SCHEMA, R.SPECIFIC_NAME,
       R.ROUTINE_CATALOG, R.ROUTINE_SCHEMA, R.ROUTINE_NAME, R.ROUTINE_TYPE,
       R.DATA_TYPE, R.CHARACTER_MAXIMUM_LENGTH, R.CHARACTER_OCTET_LENGTH,
       S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
       R.COLLATION_CATALOG, R.COLLATION_SCHEMA, R.COLLATION_NAME,
       R.NUMERIC_PRECISION, R.NUMERIC_PRECISION_RADIX, R.NUMERIC_SCALE,
       R.DATETIME_PRECISION,
       R.USER_DEFINED_TYPE_CATALOG AS TYPE_UDT_CATALOG,
       R.USER_DEFINED_TYPE_SCHEMA AS TYPE_UDT_SCHEMA,
       R.USER_DEFINED_TYPE_NAME AS TYPE_UDT_NAME,
       R.MAXIMUM_CARDINALITY, R.DTD_IDENTIFIER, R.ROUTINE_BODY,
       R.IS_DETERMINISTIC, R.SQL_DATA_ACCESS, R.IS_NULL_CALL,
       R.SCHEMA_LEVEL_ROUTINE, R.SECURITY_TYPE
     FROM DEFINITION_SCHEMA.ROUTINES AS R
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( R.COLLATION_CATALOG, R.COLLATION_SCHEMA, R.COLLATION_NAME ) )
         WHERE ( R.SPECIFIC_CATALOG, R.SPECIFIC_SCHEMA, R.SPECIFIC_NAME )
             IN ( SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME
                    FROM DEFINITION_SCHEMA.ROUTINE_PRIVILEGES
                    WHERE GRANTEE IN ( 'PUBLIC', CURRENT_USER ) )
         AND R.SPECIFIC_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    SystemView {
        name: "PARAMETERS",
        query: r"SELECT
       P.SPECIFIC_CATALOG, P.SPECIFIC_SCHEMA, P.SPECIFIC_NAME,
       P.ORDINAL_POSITION, P.PARAMETER_MODE, P.IS_RESULT, P.AS_LOCATOR,
       P.PARAMETER_NAME, P.DATA_TYPE,
       P.CHARACTER_MAXIMUM_LENGTH, P.CHARACTER_OCTET_LENGTH,
       S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
       P.COLLATION_CATALOG, P.COLLATION_SCHEMA, P.COLLATION_NAME,
       P.NUMERIC_PRECISION, P.NUMERIC_PRECISION_RADIX, P.NUMERIC_SCALE,
       P.DATETIME_PRECISION,
       P.USER_DEFINED_TYPE_CATALOG AS UDT_CATALOG,
       P.USER_DEFINED_TYPE_SCHEMA AS UDT_SCHEMA,
       P.USER_DEFINED_TYPE_NAME AS UDT_NAME,
       P.MAXIMUM_CARDINALITY, P.DTD_IDENTIFIER
     FROM DEFINITION_SCHEMA.PARAMETERS AS P
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( P.COLLATION_CATALOG, P.COLLATION_SCHEMA, P.COLLATION_NAME ) )
         WHERE ( P.SPECIFIC_CATALOG, P.SPECIFIC_SCHEMA, P.SPECIFIC_NAME )
             IN ( SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME
                    FROM ROUTINES )",
    },
    SystemView {
        name: "ROUTINE_PRIVILEGES",
        query: r"SELECT
       GRANTOR, GRANTEE, SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
         ROUTINE_CATALOG, ROUTINE_SCHEMA, ROUTINE_NAME,
         PRIVILEGE_TYPE, IS_GRANTABLE
     FROM DEFINITION_SCHEMA.ROUTINE_PRIVILEGES
         WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                 OR GRANTOR = CURRENT_USER )
         AND SPECIFIC_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    SystemView {
        name: "TRANSFORMS",
        query: r"SELECT
       UDT_CATALOG, UDT_SCHEMA, UDT_NAME,
       SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
       GROUP_NAME, TRANSFORM_TYPE
     FROM DEFINITION_SCHEMA.TRANSFORMS
         WHERE ( UDT_CATALOG, UDT_SCHEMA, UDT_NAME )
             IN ( SELECT USER_DEFINED_TYPE_CATALOG, USER_DEFINED_TYPE_SCHEMA,
                         USER_DEFINED_TYPE_NAME
                    FROM USER_DEFINED_TYPES )",
    },
];
