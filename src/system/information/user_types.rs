//! The views of the Information Schema of user-defined types and their
//! routines, as ISO/IEC 9075-11 names them. USER_DEFINED_TYPES shows each
//! distinct and structured type and UDT_PRIVILEGES each privilege on one.
//! ROUTINES, PARAMETERS and ROUTINE_PRIVILEGES show the routines each
//! type's definition makes [ISO/IEC 9075-2:2023 §11.51 GR2, GR3, §11.52]
//! and each SQL-invoked routine [§11.60], a method's type and a cast
//! function's cast among the columns ISO/IEC 9075-11:2006 draft §5.49
//! adds, and TRANSFORMS each type's transform groups. Each
//! reads its table of the Definition Schema (`definition/user_types.rs`,
//! `definition/routines.rs`). Their text is this implementation's, as
//! ISO/IEC 9075:1992 has none of them.
//!
//! A type is shown to the current user if it, PUBLIC or an enabled role
//! holds a privilege on it, as DOMAINS shows domains [ISO/IEC 9075:1992
//! §21.2.5], and a function likewise. A privilege is shown to its grantee
//! and its grantor, as TABLE_PRIVILEGES shows one [§21.2.10]. A routine's
//! definition is shown to the owner of its schema alone, as a view's is
//! [§21.2.8]. An enabled role counts as the current user does, as the
//! views of ISO/IEC 9075-11:2006 draft Clause 5 count it. Each view shows a data type
//! descriptor's character set, which the descriptor's collation is of, and
//! the columns ISO/IEC 9075-11 names for a user-defined type's name.
//!
//! ROUTINES shows every column ISO/IEC 9075-11:2006 draft §5.49 gives it,
//! CREATED and LAST_ALTERED, the timestamps of Feature T011, among them;
//! PARAMETERS every column §5.35 gives it. ROUTINES joins
//! the descriptor of a `<result cast>` from DATA_TYPE_DESCRIPTOR by
//! RESULT_CAST_FROM_DTD_IDENTIFIER, as the draft does, so its columns are
//! null, as no SQL routine has one [ISO/IEC 9075-2:2023 §11.60 SR9m i].
//!
//! ROUTINES and PARAMETERS show the columns ISO/IEC 9075-14:2006 draft
//! §20.10 and §20.11 add: an XML type's modifiers and XML Schema after
//! DTD_IDENTIFIER; those of a `<result cast>`'s type after its columns;
//! then, read from the routine's or parameter's own row
//! (`definition/routines.rs`), the descriptor of its associated string
//! type, its XML option and its XML passing mechanism, last. Corrected:
//! the draft's ROUTINES has XML_CHAR_TYPE twice, after XML_SCHEMA_ELEMENT
//! too, which its ROUTINES_S does not [§20.15]; it is shown once.

use super::SystemView;

/// The views, after those of arrays and row types.
pub(super) const VIEWS: &[SystemView] = &[
    SystemView {
        name: "USER_DEFINED_TYPES",
        query: r"SELECT
       U.USER_DEFINED_TYPE_CATALOG, U.USER_DEFINED_TYPE_SCHEMA,
       U.USER_DEFINED_TYPE_NAME, U.USER_DEFINED_TYPE_CATEGORY,
       U.IS_INSTANTIABLE, U.IS_FINAL, U.ORDERING_FORM, U.ORDERING_CATEGORY,
       U.ORDERING_ROUTINE_CATALOG, U.ORDERING_ROUTINE_SCHEMA,
       U.ORDERING_ROUTINE_NAME, U.REFERENCE_TYPE, U.DATA_TYPE,
       U.CHARACTER_MAXIMUM_LENGTH, U.CHARACTER_OCTET_LENGTH,
       S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
       U.COLLATION_CATALOG, U.COLLATION_SCHEMA, U.COLLATION_NAME,
       U.NUMERIC_PRECISION, U.NUMERIC_PRECISION_RADIX, U.NUMERIC_SCALE,
       U.DATETIME_PRECISION, U.INTERVAL_TYPE, U.INTERVAL_PRECISION, U.MAXIMUM_CARDINALITY,
       U.SOURCE_DTD_IDENTIFIER, U.REF_DTD_IDENTIFIER
     FROM DEFINITION_SCHEMA.USER_DEFINED_TYPES AS U
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( U.COLLATION_CATALOG, U.COLLATION_SCHEMA, U.COLLATION_NAME ) )
         WHERE ( U.USER_DEFINED_TYPE_CATALOG, U.USER_DEFINED_TYPE_SCHEMA,
                 U.USER_DEFINED_TYPE_NAME )
             IN ( SELECT UDT_CATALOG, UDT_SCHEMA, UDT_NAME
                    FROM DEFINITION_SCHEMA.UDT_PRIVILEGES
                    WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                            OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND U.USER_DEFINED_TYPE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    SystemView {
        name: "UDT_PRIVILEGES",
        query: r"SELECT
       GRANTOR, GRANTEE, UDT_CATALOG, UDT_SCHEMA, UDT_NAME,
         PRIVILEGE_TYPE, IS_GRANTABLE
     FROM DEFINITION_SCHEMA.UDT_PRIVILEGES
         WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
              OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES )
              OR GRANTOR = CURRENT_USER
              OR GRANTOR IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND UDT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    SystemView {
        name: "ROUTINES",
        query: r"SELECT
       R.SPECIFIC_CATALOG, R.SPECIFIC_SCHEMA, R.SPECIFIC_NAME,
       R.ROUTINE_CATALOG, R.ROUTINE_SCHEMA, R.ROUTINE_NAME, R.ROUTINE_TYPE,
       R.MODULE_CATALOG, R.MODULE_SCHEMA, R.MODULE_NAME,
       R.UDT_CATALOG, R.UDT_SCHEMA, R.UDT_NAME,
       R.DATA_TYPE, R.CHARACTER_MAXIMUM_LENGTH, R.CHARACTER_OCTET_LENGTH,
       S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
       R.COLLATION_CATALOG, R.COLLATION_SCHEMA, R.COLLATION_NAME,
       R.NUMERIC_PRECISION, R.NUMERIC_PRECISION_RADIX, R.NUMERIC_SCALE,
       R.DATETIME_PRECISION, R.INTERVAL_TYPE, R.INTERVAL_PRECISION,
       R.USER_DEFINED_TYPE_CATALOG AS TYPE_UDT_CATALOG,
       R.USER_DEFINED_TYPE_SCHEMA AS TYPE_UDT_SCHEMA,
       R.USER_DEFINED_TYPE_NAME AS TYPE_UDT_NAME,
       R.SCOPE_CATALOG, R.SCOPE_SCHEMA, R.SCOPE_NAME,
       R.MAXIMUM_CARDINALITY, R.DTD_IDENTIFIER,
       R.XML_PRIMARY_MODIFIER, R.XML_SECONDARY_MODIFIER,
       R.XML_SCHEMA_CATALOG, R.XML_SCHEMA_SCHEMA, R.XML_SCHEMA_NAME,
       R.XML_SCHEMA_NAMESPACE, R.XML_SCHEMA_ELEMENT, R.ROUTINE_BODY,
       CASE WHEN ( R.ROUTINE_CATALOG, R.ROUTINE_SCHEMA )
                   IN ( SELECT CATALOG_NAME, SCHEMA_NAME
                               FROM DEFINITION_SCHEMA.SCHEMATA
                               WHERE ( SCHEMA_OWNER = CURRENT_USER
                                    OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
            THEN R.ROUTINE_DEFINITION
            ELSE NULL
       END AS ROUTINE_DEFINITION,
       R.EXTERNAL_NAME, R.EXTERNAL_LANGUAGE, R.PARAMETER_STYLE,
       R.IS_DETERMINISTIC, R.SQL_DATA_ACCESS, R.IS_NULL_CALL, R.SQL_PATH,
       R.SCHEMA_LEVEL_ROUTINE, R.MAX_DYNAMIC_RESULT_SETS, R.IS_USER_DEFINED_CAST,
       R.IS_IMPLICITLY_INVOCABLE, R.SECURITY_TYPE,
       R.TO_SQL_SPECIFIC_CATALOG, R.TO_SQL_SPECIFIC_SCHEMA, R.TO_SQL_SPECIFIC_NAME,
       R.AS_LOCATOR, R.CREATED, R.LAST_ALTERED, R.NEW_SAVEPOINT_LEVEL, R.IS_UDT_DEPENDENT,
       DT.DATA_TYPE AS RESULT_CAST_FROM_DATA_TYPE, R.RESULT_CAST_AS_LOCATOR,
       DT.CHARACTER_MAXIMUM_LENGTH AS RESULT_CAST_CHAR_MAX_LENGTH,
       DT.CHARACTER_OCTET_LENGTH AS RESULT_CAST_CHAR_OCTET_LENGTH,
       SC.CHARACTER_SET_CATALOG AS RESULT_CAST_CHAR_SET_CATALOG,
       SC.CHARACTER_SET_SCHEMA AS RESULT_CAST_CHAR_SET_SCHEMA,
       SC.CHARACTER_SET_NAME AS RESULT_CAST_CHARACTER_SET_NAME,
       DT.COLLATION_CATALOG AS RESULT_CAST_COLLATION_CATALOG,
       DT.COLLATION_SCHEMA AS RESULT_CAST_COLLATION_SCHEMA,
       DT.COLLATION_NAME AS RESULT_CAST_COLLATION_NAME,
       DT.NUMERIC_PRECISION AS RESULT_CAST_NUMERIC_PRECISION,
       DT.NUMERIC_PRECISION_RADIX AS RESULT_CAST_NUMERIC_RADIX,
       DT.NUMERIC_SCALE AS RESULT_CAST_NUMERIC_SCALE,
       DT.DATETIME_PRECISION AS RESULT_CAST_DATETIME_PRECISION,
       DT.INTERVAL_TYPE AS RESULT_CAST_INTERVAL_TYPE,
       DT.INTERVAL_PRECISION AS RESULT_CAST_INTERVAL_PRECISION,
       DT.USER_DEFINED_TYPE_CATALOG AS RESULT_CAST_TYPE_UDT_CATALOG,
       DT.USER_DEFINED_TYPE_SCHEMA AS RESULT_CAST_TYPE_UDT_SCHEMA,
       DT.USER_DEFINED_TYPE_NAME AS RESULT_CAST_TYPE_UDT_NAME,
       DT.SCOPE_CATALOG AS RESULT_CAST_SCOPE_CATALOG,
       DT.SCOPE_SCHEMA AS RESULT_CAST_SCOPE_SCHEMA,
       DT.SCOPE_NAME AS RESULT_CAST_SCOPE_NAME,
       DT.MAXIMUM_CARDINALITY AS RESULT_CAST_MAX_CARDINALITY,
       DT.DTD_IDENTIFIER AS RESULT_CAST_DTD_IDENTIFIER,
       DT.XML_PRIMARY_MODIFIER AS RESULT_CAST_XML_PRIMARY_MODIFIER,
       DT.XML_SECONDARY_MODIFIER AS RESULT_CAST_XML_SECONDARY_MODIFIER,
       DT.XML_SCHEMA_CATALOG AS RESULT_CAST_XML_SCHEMA_CATALOG,
       DT.XML_SCHEMA_SCHEMA AS RESULT_CAST_XML_SCHEMA_SCHEMA,
       DT.XML_SCHEMA_NAME AS RESULT_CAST_XML_SCHEMA_NAME,
       DT.XML_SCHEMA_NAMESPACE AS RESULT_CAST_XML_SCHEMA_NAMESPACE,
       DT.XML_SCHEMA_ELEMENT AS RESULT_CAST_XML_SCHEMA_ELEMENT,
       R.XML_CHAR_TYPE, R.XML_CHAR_MAX_LEN, R.XML_CHAR_OCT_LEN,
       S2.CHARACTER_SET_CATALOG AS XML_CHAR_SET_CAT,
       S2.CHARACTER_SET_SCHEMA AS XML_CHAR_SET_SCH,
       S2.CHARACTER_SET_NAME AS XML_CHAR_SET_NAME,
       R.XML_CHAR_COLL_CAT, R.XML_CHAR_COLL_SCH, R.XML_CHAR_COLL_NAME,
       R.XML_STRING_DTD_IDENTIFIER AS XML_CHAR_DTD_ID,
       R.XML_OPTION, R.XML_RETURN_MECHANISM
     FROM DEFINITION_SCHEMA.ROUTINES AS R
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( R.COLLATION_CATALOG, R.COLLATION_SCHEMA, R.COLLATION_NAME ) )
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S2
           ON
           ( ( S2.COLLATION_CATALOG, S2.COLLATION_SCHEMA, S2.COLLATION_NAME )
           = ( R.XML_CHAR_COLL_CAT, R.XML_CHAR_COLL_SCH, R.XML_CHAR_COLL_NAME ) )
         LEFT JOIN
           DEFINITION_SCHEMA.DATA_TYPE_DESCRIPTOR AS DT
           ON
           ( ( R.SPECIFIC_CATALOG, R.SPECIFIC_SCHEMA, R.SPECIFIC_NAME, R.RESULT_CAST_FROM_DTD_IDENTIFIER )
           = ( DT.TABLE_OR_DOMAIN_CATALOG, DT.TABLE_OR_DOMAIN_SCHEMA, DT.TABLE_OR_DOMAIN_NAME, DT.DTD_IDENTIFIER ) )
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS SC
           ON
           ( ( SC.COLLATION_CATALOG, SC.COLLATION_SCHEMA, SC.COLLATION_NAME )
           = ( DT.COLLATION_CATALOG, DT.COLLATION_SCHEMA, DT.COLLATION_NAME ) )
         WHERE ( ( R.MODULE_NAME IS NULL
                   AND ( R.SPECIFIC_CATALOG, R.SPECIFIC_SCHEMA, R.SPECIFIC_NAME )
                     IN ( SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME
                            FROM DEFINITION_SCHEMA.ROUTINE_PRIVILEGES
                            WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                                    OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) ) )
              OR ( R.MODULE_NAME IS NOT NULL
                   AND ( R.MODULE_CATALOG, R.MODULE_SCHEMA, R.MODULE_NAME )
                     IN ( SELECT MP.MODULE_CATALOG, MP.MODULE_SCHEMA, MP.MODULE_NAME
                            FROM DEFINITION_SCHEMA.MODULE_PRIVILEGES AS MP
                            WHERE ( MP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                                    OR MP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) ) ) )
         AND R.SPECIFIC_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    SystemView {
        name: "PARAMETERS",
        query: r"SELECT
       P.SPECIFIC_CATALOG, P.SPECIFIC_SCHEMA, P.SPECIFIC_NAME,
       P.ORDINAL_POSITION, P.PARAMETER_MODE, P.IS_RESULT, P.AS_LOCATOR,
       P.PARAMETER_NAME,
       P.FROM_SQL_SPECIFIC_CATALOG, P.FROM_SQL_SPECIFIC_SCHEMA, P.FROM_SQL_SPECIFIC_NAME,
       P.TO_SQL_SPECIFIC_CATALOG, P.TO_SQL_SPECIFIC_SCHEMA, P.TO_SQL_SPECIFIC_NAME,
       P.DATA_TYPE,
       P.CHARACTER_MAXIMUM_LENGTH, P.CHARACTER_OCTET_LENGTH,
       S.CHARACTER_SET_CATALOG, S.CHARACTER_SET_SCHEMA, S.CHARACTER_SET_NAME,
       P.COLLATION_CATALOG, P.COLLATION_SCHEMA, P.COLLATION_NAME,
       P.NUMERIC_PRECISION, P.NUMERIC_PRECISION_RADIX, P.NUMERIC_SCALE,
       P.DATETIME_PRECISION, P.INTERVAL_TYPE, P.INTERVAL_PRECISION,
       P.USER_DEFINED_TYPE_CATALOG AS UDT_CATALOG,
       P.USER_DEFINED_TYPE_SCHEMA AS UDT_SCHEMA,
       P.USER_DEFINED_TYPE_NAME AS UDT_NAME,
       P.SCOPE_CATALOG, P.SCOPE_SCHEMA, P.SCOPE_NAME,
       P.MAXIMUM_CARDINALITY, P.DTD_IDENTIFIER,
       P.XML_PRIMARY_MODIFIER, P.XML_SECONDARY_MODIFIER,
       P.XML_SCHEMA_CATALOG, P.XML_SCHEMA_SCHEMA, P.XML_SCHEMA_NAME,
       P.XML_SCHEMA_NAMESPACE, P.XML_SCHEMA_ELEMENT,
       P.XML_CHAR_TYPE, P.XML_CHAR_MAX_LEN, P.XML_CHAR_OCT_LEN,
       S2.CHARACTER_SET_CATALOG AS XML_CHAR_SET_CAT,
       S2.CHARACTER_SET_SCHEMA AS XML_CHAR_SET_SCH,
       S2.CHARACTER_SET_NAME AS XML_CHAR_SET_NAME,
       P.XML_CHAR_COLL_CAT, P.XML_CHAR_COLL_SCH, P.XML_CHAR_COLL_NAME,
       P.XML_STRING_DTD_IDENTIFIER AS XML_CHAR_DTD_ID,
       P.XML_OPTION, P.XML_PASSING_MECHANISM, P.PARAMETER_DEFAULT
     FROM DEFINITION_SCHEMA.PARAMETERS AS P
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S
           ON
           ( ( S.COLLATION_CATALOG, S.COLLATION_SCHEMA, S.COLLATION_NAME )
           = ( P.COLLATION_CATALOG, P.COLLATION_SCHEMA, P.COLLATION_NAME ) )
         LEFT JOIN
           DEFINITION_SCHEMA.COLLATIONS AS S2
           ON
           ( ( S2.COLLATION_CATALOG, S2.COLLATION_SCHEMA, S2.COLLATION_NAME )
           = ( P.XML_CHAR_COLL_CAT, P.XML_CHAR_COLL_SCH, P.XML_CHAR_COLL_NAME ) )
         WHERE ( P.SPECIFIC_CATALOG, P.SPECIFIC_SCHEMA, P.SPECIFIC_NAME )
             IN ( SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME
                    FROM ROUTINES )",
    },
    SystemView {
        name: "ROUTINE_PRIVILEGES",
        query: r"SELECT
       GRANTOR, GRANTEE, SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
         ROUTINE_CATALOG, ROUTINE_SCHEMA, ROUTINE_NAME,
         PRIVILEGE_TYPE, IS_GRANTABLE
     FROM DEFINITION_SCHEMA.ROUTINE_PRIVILEGES
         WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
              OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES )
              OR GRANTOR = CURRENT_USER
              OR GRANTOR IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND SPECIFIC_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    SystemView {
        name: "TRANSFORMS",
        query: r"SELECT
       UDT_CATALOG, UDT_SCHEMA, UDT_NAME,
       SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
       GROUP_NAME, TRANSFORM_TYPE
     FROM DEFINITION_SCHEMA.TRANSFORMS
         WHERE ( UDT_CATALOG, UDT_SCHEMA, UDT_NAME )
             IN ( SELECT USER_DEFINED_TYPE_CATALOG, USER_DEFINED_TYPE_SCHEMA,
                         USER_DEFINED_TYPE_NAME
                    FROM USER_DEFINED_TYPES )",
    },
];
