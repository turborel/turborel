//! \[EXTENSION\] The views of the Information Schema that ISO/IEC 9075
//! does not define, each over the Definition Schema's tables of its kind
//! [ISO/IEC 9075:1992 §21.1]. Each shows what the current user, PUBLIC or
//! an enabled role holds a privilege on, as TABLES does.

use super::SystemView;

/// The views, after the standard's.
pub(super) const VIEWS: &[SystemView] = &[
    // [EXTENSION] [ISO/IEC 9075:1992 §21.1] TABLE_OPTIONS (RULES.md D41): the
    // options of the tables the current user has a privilege on, as TABLES
    // [§21.2.7] chooses them.
    SystemView {
        name: "TABLE_OPTIONS",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, ENGINE_NAME, OPTION_NAME,
       DECLARED_BY, OPTION_VALUE, VALUE_SOURCE, DEFAULT_VALUE, VALUE_KIND, CHANGED_BY,
       DESCRIPTION
     FROM DEFINITION_SCHEMA.TABLE_OPTIONS
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN (
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
               UNION
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [EXTENSION] [ISO/IEC 9075-2:2023 §4.16.1] PERIODS: the periods of the
    // tables the current user has a privilege on.
    SystemView {
        name: "PERIODS",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, PERIOD_NAME,
       START_COLUMN_NAME, END_COLUMN_NAME,
       CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME
     FROM DEFINITION_SCHEMA.PERIODS
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN (
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
               UNION
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [EXTENSION] [ISO/IEC 9075:1992 §21.1] INDEXES (RULES.md D34): the
    // indexes of the tables the current user has a privilege on.
    SystemView {
        name: "INDEXES",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, INDEX_NAME, METHOD_NAME,
       IS_UNIQUE, COLUMN_NAMES
     FROM DEFINITION_SCHEMA.INDEXES
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN (
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
               UNION
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [EXTENSION] [ISO/IEC 9075:1992 §21.1] INDEX_OPTIONS (RULES.md D41): the
    // options of those indexes.
    SystemView {
        name: "INDEX_OPTIONS",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, INDEX_NAME, METHOD_NAME,
       OPTION_NAME, DECLARED_BY, OPTION_VALUE, VALUE_SOURCE, DEFAULT_VALUE, VALUE_KIND,
       CHANGED_BY, DESCRIPTION
     FROM DEFINITION_SCHEMA.INDEX_OPTIONS
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN (
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
               UNION
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [EXTENSION] ADJACENCY_INDEXES (RULES.md D141): the
    // adjacency indexes of those tables, each with the options that lay
    // out its key and bound its compacted adjacency.
    SystemView {
        name: "ADJACENCY_INDEXES",
        query: r"SELECT
       I.TABLE_CATALOG, I.TABLE_SCHEMA, I.TABLE_NAME, I.INDEX_NAME, I.COLUMN_NAMES,
       ( SELECT O.OPTION_VALUE FROM INDEX_OPTIONS AS O
          WHERE O.INDEX_NAME = I.INDEX_NAME AND O.OPTION_NAME = 'ADJACENCY.SOURCE_COLUMNS' ) AS SOURCE_COLUMNS,
       ( SELECT O.OPTION_VALUE FROM INDEX_OPTIONS AS O
          WHERE O.INDEX_NAME = I.INDEX_NAME AND O.OPTION_NAME = 'ADJACENCY.INCLUDE' ) AS INCLUDED_COLUMNS,
       ( SELECT O.OPTION_VALUE FROM INDEX_OPTIONS AS O
          WHERE O.INDEX_NAME = I.INDEX_NAME AND O.OPTION_NAME = 'ADJACENCY.DIRECTION' ) AS DIRECTION,
       ( SELECT O.OPTION_VALUE FROM INDEX_OPTIONS AS O
          WHERE O.INDEX_NAME = I.INDEX_NAME AND O.OPTION_NAME = 'ADJACENCY.CSR_BYTES' ) AS CSR_BYTES
     FROM INDEXES AS I
         WHERE I.METHOD_NAME = 'adjacency'",
    },
    // [EXTENSION] PARTITIONED_TABLES (RULES.md D153): the partitioned
    // tables the current user has a privilege on, each its strategy, key
    // and number of partitions.
    SystemView {
        name: "PARTITIONED_TABLES",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, STRATEGY, KEY_PARTS, PARTITION_COUNT
     FROM DEFINITION_SCHEMA.PARTITIONED_TABLES
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN (
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
               UNION
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [EXTENSION] PARTITIONS (RULES.md D153): the partitions the current
    // user has a privilege on, each the table it is a partition of, its
    // bound, its level and whether it is partitioned again.
    SystemView {
        name: "PARTITIONS",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
       PARENT_TABLE_CATALOG, PARENT_TABLE_SCHEMA, PARENT_TABLE_NAME,
       BOUND, PARTITION_LEVEL, IS_PARTITIONED
     FROM DEFINITION_SCHEMA.PARTITIONS
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN (
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
               UNION
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [EXTENSION] PARTITION_INDEXES (RULES.md D158): of each index of a
    // partitioned table the current user has a privilege on, the index it
    // made on each partition.
    SystemView {
        name: "PARTITION_INDEXES",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, TEMPLATE_NAME, METHOD_NAME, IS_UNIQUE,
       PARTITION_CATALOG, PARTITION_SCHEMA, PARTITION_NAME, INDEX_NAME
     FROM DEFINITION_SCHEMA.PARTITION_INDEXES
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN (
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
               UNION
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
];
