//! The views of the Information Schema of ISO/IEC 9075:1992 that describe
//! schemas, domains, tables, views, columns and privileges [§21.2.4 to
//! §21.2.12], as the standard defines them, with the columns ISO/IEC
//! 9075-11:2006 draft Clause 5 adds to each, each noted at its view.

use super::SystemView;

/// The views, in the standard's order.
pub(super) const VIEWS: &[SystemView] = &[
    // [ISO/IEC 9075:1992 §21.2.4] SCHEMATA; with SQL_PATH, as ISO/IEC
    // 9075-11:2006 draft §5.50 adds it.
    SystemView {
        name: "SCHEMATA",
        query: r"SELECT
         CATALOG_NAME, SCHEMA_NAME, SCHEMA_OWNER,
         DEFAULT_CHARACTER_SET_CATALOG, DEFAULT_CHARACTER_SET_SCHEMA,
         DEFAULT_CHARACTER_SET_NAME, SQL_PATH
       FROM DEFINITION_SCHEMA.SCHEMATA
       WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CATALOG_NAME
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.5] DOMAINS; with each domain's interval
    // fields and precision, maximum cardinality and the identifier of its
    // data type descriptor, as ISO/IEC 9075-11:2006 draft §5.28 adds them, and its XML modifiers and XML Schema, as
    // [ISO/IEC 9075-14:2006 draft §20.5] does.
    SystemView {
        name: "DOMAINS",
        query: r"SELECT DISTINCT
       DOMAIN_CATALOG, DOMAIN_SCHEMA, DOMAIN_NAME,
       DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, CHARACTER_OCTET_LENGTH,
       COLLATION_CATALOG, COLLATION_SCHEMA,COLLATION_NAME,
       CHARACTER_SET_CATALOG, CHARACTER_SET_SCHEMA, CHARACTER_SET_NAME,
       NUMERIC_PRECISION, NUMERIC_PRECISION_RADIX, NUMERIC_SCALE,
       DATETIME_PRECISION, INTERVAL_TYPE, INTERVAL_PRECISION, DOMAIN_DEFAULT,
       MAXIMUM_CARDINALITY, DTD_IDENTIFIER, XML_PRIMARY_MODIFIER, XML_SECONDARY_MODIFIER,
       XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME, XML_SCHEMA_NAMESPACE, XML_SCHEMA_ELEMENT
     FROM DEFINITION_SCHEMA.DOMAINS
          JOIN
            DEFINITION_SCHEMA.DATA_TYPE_DESCRIPTOR AS D
            LEFT JOIN
            DEFINITION_SCHEMA.COLLATIONS AS S
            USING ( COLLATION_CATALOG, COLLATION_SCHEMA, COLLATION_NAME )
          ON
            ( ( DOMAIN_CATALOG, DOMAIN_SCHEMA, DOMAIN_NAME, '' )
            = ( TABLE_OR_DOMAIN_CATALOG, TABLE_OR_DOMAIN_SCHEMA,
                  TABLE_OR_DOMAIN_NAME, COLUMN_NAME ) )
       WHERE
             ( ( DOMAIN_CATALOG, DOMAIN_SCHEMA, DOMAIN_NAME, 'DOMAIN' )
               IN
               ( SELECT OBJECT_CATALOG, OBJECT_SCHEMA, OBJECT_NAME, OBJECT_TYPE
                 FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES
                   WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                           OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
               OR
               ( DOMAIN_CATALOG, DOMAIN_SCHEMA, DOMAIN_NAME ) IN
                 ( SELECT DOMAIN_CATALOG, DOMAIN_SCHEMA, DOMAIN_NAME
                   FROM COLUMNS ) )
         AND DOMAIN_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.6] DOMAIN_CONSTRAINTS; corrected: the source's "SCHEMA_NAME S)" read as "S.SCHEMA_NAME )".
    SystemView {
        name: "DOMAIN_CONSTRAINTS",
        query: r"SELECT DISTINCT
       CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME,
       DOMAIN_CATALOG, DOMAIN_SCHEMA, DOMAIN_NAME,
       IS_DEFERRABLE, INITIALLY_DEFERRED
     FROM DEFINITION_SCHEMA.DOMAIN_CONSTRAINTS
          JOIN
            DEFINITION_SCHEMA.SCHEMATA AS S
               ON
               ( ( CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA )
               = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
       WHERE
         ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CONSTRAINT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.7] TABLES; with what makes a table typed,
    // whether it is insertable-into and its commit action, as ISO/IEC
    // 9075-11:2006 draft §5.61 adds them.
    SystemView {
        name: "TABLES",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE,
       SELF_REFERENCING_COLUMN_NAME, REFERENCE_GENERATION,
       USER_DEFINED_TYPE_CATALOG, USER_DEFINED_TYPE_SCHEMA, USER_DEFINED_TYPE_NAME,
       IS_INSERTABLE_INTO, IS_TYPED, COMMIT_ACTION
     FROM DEFINITION_SCHEMA.TABLES
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN (
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
               UNION
               SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                  WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.8] VIEWS; with INSERTABLE_INTO, as ISO/IEC
    // 9075-11:2006 draft §5.76 adds it.
    SystemView {
        name: "VIEWS",
        query: r"SELECT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
       CASE WHEN ( TABLE_CATALOG, TABLE_SCHEMA )
                   IN ( SELECT CATALOG_NAME, SCHEMA_NAME
                               FROM DEFINITION_SCHEMA.SCHEMATA
                               WHERE ( SCHEMA_OWNER = CURRENT_USER
                                    OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
            THEN VIEW_DEFINITION
            ELSE NULL
       END AS VIEW_DEFINITION,
         CHECK_OPTION, IS_UPDATABLE,
         ( SELECT IS_INSERTABLE_INTO
           FROM DEFINITION_SCHEMA.TABLES AS T
           WHERE ( V.TABLE_CATALOG, V.TABLE_SCHEMA, V.TABLE_NAME )
               = ( T.TABLE_CATALOG, T.TABLE_SCHEMA, T.TABLE_NAME )
         ) AS INSERTABLE_INTO
     FROM DEFINITION_SCHEMA.VIEWS AS V
         WHERE ( TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME )
           IN ( SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
                FROM TABLES )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.9] COLUMNS; with each column's interval fields and precision, scope,
    // self-referencing, identity, generation and updatability, maximum cardinality and, of a column of
    // no domain, the identifier of its data type descriptor, as ISO/IEC 9075-11:2006 draft §5.21 adds
    // them; its XML
    // modifiers and XML Schema [ISO/IEC 9075-14:2006 draft §20.4].
    SystemView {
        name: "COLUMNS",
        query: r"SELECT DISTINCT
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
       C.COLUMN_NAME, ORDINAL_POSITION,
       CASE WHEN EXISTS ( SELECT *
              FROM DEFINITION_SCHEMA.SCHEMATA AS S
              WHERE ( TABLE_CATALOG, TABLE_SCHEMA )
                  = (S.CATALOG_NAME, S.SCHEMA_NAME )
                AND ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
             THEN COLUMN_DEFAULT
            ELSE NULL
       END AS COLUMN_DEFAULT,
       IS_NULLABLE,
       COALESCE (D1.DATA_TYPE, D2.DATA_TYPE) AS DATA_TYPE,
       COALESCE (D1.CHARACTER_MAXIMUM_LENGTH, D2.CHARACTER_MAXIMUM_LENGTH)
           AS CHARACTER_MAXIMUM_LENGTH,
       COALESCE (D1.CHARACTER_OCTET_LENGTH, D2.CHARACTER_OCTET_LENGTH)
                    AS CHARACTER_OCTET_LENGTH,
       COALESCE (D1.NUMERIC_PRECISION, D2.NUMERIC_PRECISION)
                    AS NUMERIC_PRECISION,
       COALESCE (D1.NUMERIC_PRECISION_RADIX, D2.NUMERIC_PRECISION_RADIX)
                    AS NUMERIC_PRECISION_RADIX,
       COALESCE (D1.NUMERIC_SCALE, D2.NUMERIC_SCALE) AS NUMERIC_SCALE,
       COALESCE (D1.DATETIME_PRECISION, D2.DATETIME_PRECISION) AS
     DATETIME_PRECISION,
       COALESCE (D1.INTERVAL_TYPE, D2.INTERVAL_TYPE) AS INTERVAL_TYPE,
       COALESCE (D1.INTERVAL_PRECISION, D2.INTERVAL_PRECISION) AS INTERVAL_PRECISION,
       COALESCE (C1.CHARACTER_SET_CATALOG, C2.CHARACTER_SET_CATALOG)
                    AS CHARACTER_SET_CATALOG,
       COALESCE (C1.CHARACTER_SET_SCHEMA, C2.CHARACTER_SET_SCHEMA)
                    AS CHARACTER_SET_SCHEMA,
       COALESCE (C1.CHARACTER_SET_NAME, C2.CHARACTER_SET_NAME) AS
     CHARACTER_SET_NAME,
       COALESCE (D1.COLLATION_CATALOG, D2.COLLATION_CATALOG) AS
     COLLATION_CATALOG,
       COALESCE (D1.COLLATION_SCHEMA, D2.COLLATION_SCHEMA) AS
     COLLATION_SCHEMA,
       COALESCE (D1.COLLATION_NAME, D2.COLLATION_NAME) AS
     COLLATION_NAME,
       DOMAIN_CATALOG, DOMAIN_SCHEMA, DOMAIN_NAME,
       D1.USER_DEFINED_TYPE_CATALOG AS UDT_CATALOG,
       D1.USER_DEFINED_TYPE_SCHEMA AS UDT_SCHEMA,
       D1.USER_DEFINED_TYPE_NAME AS UDT_NAME,
       D1.SCOPE_CATALOG, D1.SCOPE_SCHEMA, D1.SCOPE_NAME, IS_SELF_REFERENCING,
       IS_IDENTITY, IDENTITY_GENERATION, IDENTITY_START, IDENTITY_INCREMENT,
       IDENTITY_MAXIMUM, IDENTITY_MINIMUM, IDENTITY_CYCLE,
       IS_GENERATED, GENERATION_EXPRESSION, IS_UPDATABLE,
       COALESCE (D1.MAXIMUM_CARDINALITY, D2.MAXIMUM_CARDINALITY)
                    AS MAXIMUM_CARDINALITY,
       D1.DTD_IDENTIFIER,
       COALESCE (D1.XML_PRIMARY_MODIFIER, D2.XML_PRIMARY_MODIFIER) AS XML_PRIMARY_MODIFIER,
       COALESCE (D1.XML_SECONDARY_MODIFIER, D2.XML_SECONDARY_MODIFIER) AS XML_SECONDARY_MODIFIER,
       COALESCE (D1.XML_SCHEMA_CATALOG, D2.XML_SCHEMA_CATALOG) AS XML_SCHEMA_CATALOG,
       COALESCE (D1.XML_SCHEMA_SCHEMA, D2.XML_SCHEMA_SCHEMA) AS XML_SCHEMA_SCHEMA,
       COALESCE (D1.XML_SCHEMA_NAME, D2.XML_SCHEMA_NAME) AS XML_SCHEMA_NAME,
       COALESCE (D1.XML_SCHEMA_NAMESPACE, D2.XML_SCHEMA_NAMESPACE) AS XML_SCHEMA_NAMESPACE,
       COALESCE (D1.XML_SCHEMA_ELEMENT, D2.XML_SCHEMA_ELEMENT) AS XML_SCHEMA_ELEMENT
     FROM DEFINITION_SCHEMA.COLUMNS AS C
         LEFT JOIN
           DEFINITION_SCHEMA.DATA_TYPE_DESCRIPTOR AS D1
             LEFT JOIN
               DEFINITION_SCHEMA.COLLATIONS AS C1
               ON
               ( ( C1.COLLATION_CATALOG, C1.COLLATION_SCHEMA, C1.COLLATION_NAME )
               = ( D1.COLLATION_CATALOG, D1.COLLATION_SCHEMA, D1.COLLATION_NAME ) )
         ON
           ( ( C.TABLE_CATALOG, C.TABLE_SCHEMA, C.TABLE_NAME, C.COLUMN_NAME )
           = ( D1.TABLE_OR_DOMAIN_CATALOG, D1.TABLE_OR_DOMAIN_SCHEMA,
                 D1.TABLE_OR_DOMAIN_NAME, D1.COLUMN_NAME ) )
         LEFT JOIN
           DEFINITION_SCHEMA.DATA_TYPE_DESCRIPTOR AS D2
             LEFT JOIN
               DEFINITION_SCHEMA.COLLATIONS AS C2
               ON
               ( ( C2.COLLATION_CATALOG, C2.COLLATION_SCHEMA, C2.COLLATION_NAME )
               = ( D2.COLLATION_CATALOG, D2.COLLATION_SCHEMA, D2.COLLATION_NAME ) )
         ON
           ( ( C.DOMAIN_CATALOG, C.DOMAIN_SCHEMA, C.DOMAIN_NAME )
           = ( D2.TABLE_OR_DOMAIN_CATALOG, D2.TABLE_OR_DOMAIN_SCHEMA,
                 D2.TABLE_OR_DOMAIN_NAME ) )
         WHERE ( C.TABLE_CATALOG, C.TABLE_SCHEMA, C.TABLE_NAME, C.COLUMN_NAME )
           IN
             ( SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME
                  FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
                    WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                            OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND C.TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.10] TABLE_PRIVILEGES.
    SystemView {
        name: "TABLE_PRIVILEGES",
        query: r"SELECT
       GRANTOR, GRANTEE, TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
         PRIVILEGE_TYPE, IS_GRANTABLE, WITH_HIERARCHY
     FROM DEFINITION_SCHEMA.TABLE_PRIVILEGES
         WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
              OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES )
              OR GRANTOR = CURRENT_USER
              OR GRANTOR IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.11] COLUMN_PRIVILEGES.
    SystemView {
        name: "COLUMN_PRIVILEGES",
        query: r"SELECT
       GRANTOR, GRANTEE, TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME,
         PRIVILEGE_TYPE, IS_GRANTABLE
     FROM DEFINITION_SCHEMA.COLUMN_PRIVILEGES
         WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
              OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES )
              OR GRANTOR = CURRENT_USER
              OR GRANTOR IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND TABLE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.12] USAGE_PRIVILEGES.
    SystemView {
        name: "USAGE_PRIVILEGES",
        query: r"SELECT
       GRANTOR, GRANTEE, OBJECT_CATALOG, OBJECT_SCHEMA, OBJECT_NAME,
         OBJECT_TYPE, 'USAGE' AS PRIVILEGE_TYPE, IS_GRANTABLE
     FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES
         WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
              OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES )
              OR GRANTOR = CURRENT_USER
              OR GRANTOR IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND OBJECT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
];
