//! [ISO/IEC 9075-11:2006 draft §5.77] The short name views: the
//! Information Schema's views again, under names and with columns of
//! identifiers short enough for an SQL-implementation without Feature F391,
//! "Long identifiers" [§4.2]. Each reads its view of the Information Schema
//! as the draft defines it, as a user's query would, so it shows the rows
//! that view shows the user. With them what ISO/IEC 9075-4:2006 draft
//! §18.8 and ISO/IEC 9075-14:2006 draft §20.15 add: MODULE_COL_USAGE and
//! MODULES_S; the columns of an XML type in each view that describes a
//! data type; and XML_SCHEMAS_S, XML_SCH_NSPACES_S and XML_SCH_ELEMENTS_S.
//!
//! The draft gives each a `<view column list>`; here each column is named
//! by an `<as clause>` instead, which names it as the list would
//! [ISO/IEC 9075:1992 §7.9 SR9a, §11.19 GR1]. A column the draft takes from
//! a column its view does not have here is left out, as is a short name
//! view of a view not defined here: COLLATION_APPLIC_S, COL_COL_USAGE,
//! CONSTR_ROUT_USE_S, ROUT_ROUT_USAGE_S, ROUT_SEQ_USAGE_S,
//! ROUTINE_COL_USAGE, ROUT_TABLE_USAGE, SQL_IMPL_INFO and
//! SQL_SIZING_PROFS. The interval columns are left out of each view that
//! describes a data type, as no view here has them. Each slip of the draft
//! corrected is noted at its view.

