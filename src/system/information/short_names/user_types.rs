//! [ISO/IEC 9075-11:2006 draft §5.77] The short name views of the views of
//! user-defined types and routines: UDT_S, ROUTINES_S and PARAMETERS_S,
//! the last two with the columns of an XML type ISO/IEC 9075-14:2006 draft
//! §20.15 adds. ROUTINES_S leaves out the columns of an external routine,
//! a `<result cast>`, a transform, a timestamp and a result set, and
//! PARAMETERS_S those of a transform, as ROUTINES and PARAMETERS have
//! none. ROUTINES_S has XML_CHAR_TYPE once, among the columns of the
//! associated string type at its end, where the draft's `<view column
//! list>` has it, and reads it from the one XML_CHAR_TYPE ROUTINES has.

use super::SystemView;

/// The views, in the order of the views they read.
