//! [ISO/IEC 9075-11:2006 draft §5.77] The short name views of the views of
//! usage and of the collations' applicability: COLLATION_APPLIC_S,
//! COL_COL_USAGE, CONSTR_ROUT_USE_S, ROUT_ROUT_USAGE_S, ROUT_SEQ_USAGE_S,
//! ROUTINE_COL_USAGE and ROUT_TABLE_USAGE.

use super::SystemView;

/// The views, in the draft's order.
pub(super) const VIEWS: &[SystemView] = &[
    // [ISO/IEC 9075-11:2006 draft §5.77] COLLATION_APPLIC_S.
    SystemView {
        name: "COLLATION_APPLIC_S",
        query: r"SELECT COLLATION_CATALOG, COLLATION_SCHEMA, COLLATION_NAME,
           CHARACTER_SET_CATALOG AS CHAR_SET_CATALOG,
           CHARACTER_SET_SCHEMA AS CHAR_SET_SCHEMA, CHARACTER_SET_NAME
    FROM INFORMATION_SCHEMA.COLLATION_CHARACTER_SET_APPLICABILITY",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] COL_COL_USAGE.
    SystemView {
        name: "COL_COL_USAGE",
        query: r"SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
           COLUMN_NAME, DEPENDENT_COLUMN
    FROM INFORMATION_SCHEMA.COLUMN_COLUMN_USAGE",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] CONSTR_ROUT_USE_S.
    SystemView {
        name: "CONSTR_ROUT_USE_S",
        query: r"SELECT CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME,
           SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME
    FROM INFORMATION_SCHEMA.CHECK_CONSTRAINT_ROUTINE_USAGE",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] ROUT_ROUT_USAGE_S.
    SystemView {
        name: "ROUT_ROUT_USAGE_S",
        query: r"SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
           ROUTINE_CATALOG, RRU.ROUTINE_SCHEMA, RRU.ROUTINE_NAME
    FROM INFORMATION_SCHEMA.ROUTINE_ROUTINE_USAGE RRU",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] ROUT_SEQ_USAGE_S.
    SystemView {
        name: "ROUT_SEQ_USAGE_S",
        query: r"SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
           SEQUENCE_CATALOG, SEQUENCE_SCHEMA, SEQUENCE_NAME
    FROM INFORMATION_SCHEMA.ROUTINE_SEQUENCE_USAGE",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] ROUTINE_COL_USAGE.
    SystemView {
        name: "ROUTINE_COL_USAGE",
        query: r"SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
           ROUTINE_CATALOG, ROUTINE_SCHEMA, ROUTINE_NAME,
           TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
           COLUMN_NAME
    FROM INFORMATION_SCHEMA.ROUTINE_COLUMN_USAGE",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] ROUT_TABLE_USAGE.
    SystemView {
        name: "ROUT_TABLE_USAGE",
        query: r"SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
           ROUTINE_CATALOG, ROUTINE_SCHEMA, ROUTINE_NAME,
           TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
    FROM INFORMATION_SCHEMA.ROUTINE_TABLE_USAGE",
    },
];
