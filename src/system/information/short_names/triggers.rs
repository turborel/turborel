//! [ISO/IEC 9075-11:2006 draft §5.77] The short name views of the views of
//! triggers: TRIGGERS_S, TRIG_UPDATE_COLS, TRIG_TABLE_USAGE,
//! TRIG_COLUMN_USAGE, TRIG_ROUT_USAGE_S and TRIG_SEQ_USAGE_S. The draft
//! grants SELECT on TRIGGER_TABLE_USAGE after defining TRIG_TABLE_USAGE,
//! read as a grant on TRIG_TABLE_USAGE, as on every other such view.

use super::SystemView;

/// The views, in the order of the views they read.
pub(super) const VIEWS: &[SystemView] = &[
    // [ISO/IEC 9075-11:2006 draft §5.77] TRIGGERS_S.
    SystemView {
        name: "TRIGGERS_S",
        query: r"SELECT TRIGGER_CATALOG, TRIGGER_SCHEMA, TRIGGER_NAME,
           EVENT_MANIPULATION, EVENT_OBJECT_CATALOG AS EVENT_OBJECT_CAT,
           EVENT_OBJECT_SCHEMA AS EVENT_OBJECT_SCH,
           EVENT_OBJECT_TABLE, ACTION_ORDER, ACTION_CONDITION,
           ACTION_STATEMENT, ACTION_ORIENTATION, ACTION_TIMING,
           ACTION_REFERENCE_OLD_TABLE AS ACT_REF_OLD_TABLE,
           ACTION_REFERENCE_NEW_TABLE AS ACT_REF_NEW_TABLE,
           ACTION_REFERENCE_OLD_ROW AS ACT_REF_OLD_ROW,
           ACTION_REFERENCE_NEW_ROW AS ACT_REF_NEW_ROW, CREATED
    FROM INFORMATION_SCHEMA.TRIGGERS",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] TRIG_UPDATE_COLS.
    SystemView {
        name: "TRIG_UPDATE_COLS",
        query: r"SELECT TRIGGER_CATALOG, TRIGGER_SCHEMA, TRIGGER_NAME,
           EVENT_OBJECT_CATALOG AS EVENT_OBJECT_CAT,
           EVENT_OBJECT_SCHEMA AS EVENT_OBJECT_SCH, EVENT_OBJECT_TABLE,
           EVENT_OBJECT_COLUMN AS EVENT_OBJECT_COL
    FROM INFORMATION_SCHEMA.TRIGGERED_UPDATE_COLUMNS",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] TRIG_TABLE_USAGE.
    SystemView {
        name: "TRIG_TABLE_USAGE",
        query: r"SELECT TRIGGER_CATALOG, TRIGGER_SCHEMA, TRIGGER_NAME,
           TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
    FROM INFORMATION_SCHEMA.TRIGGER_TABLE_USAGE",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] TRIG_COLUMN_USAGE.
    SystemView {
        name: "TRIG_COLUMN_USAGE",
        query: r"SELECT TRIGGER_CATALOG, TRIGGER_SCHEMA, TRIGGER_NAME,
           TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME
    FROM INFORMATION_SCHEMA.TRIGGER_COLUMN_USAGE",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] TRIG_ROUT_USAGE_S.
    SystemView {
        name: "TRIG_ROUT_USAGE_S",
        query: r"SELECT TRIGGER_CATALOG, TRIGGER_SCHEMA, TRIGGER_NAME,
           SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME
    FROM INFORMATION_SCHEMA.TRIGGER_ROUTINE_USAGE",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] TRIG_SEQ_USAGE_S.
    SystemView {
        name: "TRIG_SEQ_USAGE_S",
        query: r"SELECT TRIGGER_CATALOG, TRIGGER_SCHEMA, TRIGGER_NAME,
           SEQUENCE_CATALOG, SEQUENCE_SCHEMA, SEQUENCE_NAME
    FROM INFORMATION_SCHEMA.TRIGGER_SEQUENCE_USAGE",
    },
];
