//! [ISO/IEC 9075-11:2006 draft §5.77] The short name views of the views of
//! structured types and reference types: ATTRIBUTES_S, METHOD_SPECS and
//! METHOD_SPEC_PARAMS, each with the columns of an XML type ISO/IEC
//! 9075-14:2006 draft §20.15 appends; REFERENCED_TYPES_S; and
//! TABLE_METHOD_PRIVS. METHOD_SPECS leaves out the timestamps and the
//! columns of a `<result cast>`, as METHOD_SPECIFICATIONS has none. The
//! XML draft names the methods' views METHOD_SPECS_S and
//! METHOD_SPEC_PARAMS_S, read as the views of those names here.

use super::SystemView;

/// The views, in the order of the views they read.
pub(super) const VIEWS: &[SystemView] = &[
    // [ISO/IEC 9075-11:2006 draft §5.77] ATTRIBUTES_S; with the XML columns
    // [ISO/IEC 9075-14:2006 draft §20.15]. Corrected: the draft's select
    // list begins UDT_NAME, ORDINAL_POSITION, ATTRIBUTE_DEFAULT,
    // IS_NULLABLE, a column ATTRIBUTES has not, where its `<view column
    // list>` has ATTRIBUTE_NAME before ORDINAL_POSITION; read as the list.
    SystemView {
        name: "ATTRIBUTES_S",
        query: r"SELECT UDT_CATALOG, UDT_SCHEMA, UDT_NAME,
           ATTRIBUTE_NAME, ORDINAL_POSITION, ATTRIBUTE_DEFAULT,
           DATA_TYPE, CHARACTER_MAXIMUM_LENGTH AS CHAR_MAX_LENGTH,
           CHARACTER_OCTET_LENGTH AS CHAR_OCTET_LENGTH,
           CHARACTER_SET_CATALOG AS CHAR_SET_CATALOG,
           CHARACTER_SET_SCHEMA AS CHAR_SET_SCHEMA, CHARACTER_SET_NAME,
           COLLATION_CATALOG, COLLATION_SCHEMA, COLLATION_NAME,
           NUMERIC_PRECISION, NUMERIC_PRECISION_RADIX AS NUMERIC_PREC_RADIX, NUMERIC_SCALE,
           DATETIME_PRECISION,
           ATTRIBUTE_UDT_CATALOG AS ATT_UDT_CAT, ATTRIBUTE_UDT_SCHEMA AS ATT_UDT_SCHEMA,
           ATTRIBUTE_UDT_NAME AS ATT_UDT_NAME,
           SCOPE_CATALOG, SCOPE_SCHEMA, SCOPE_NAME,
           MAXIMUM_CARDINALITY AS MAX_CARDINALITY, DTD_IDENTIFIER,
           IS_DERIVED_REFERENCE_ATTRIBUTE AS IS_DERIVED_REF_ATT,
           XML_PRIMARY_MODIFIER AS XML_PRIMARY_MOD,
           XML_SECONDARY_MODIFIER AS XML_SECONDARY_MOD, XML_SCHEMA_CATALOG,
           XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME,
           XML_SCHEMA_NAMESPACE AS XML_SCHEMA_NSPACE, XML_SCHEMA_ELEMENT
    FROM INFORMATION_SCHEMA.ATTRIBUTES",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] METHOD_SPECS; with the XML columns
    // of the result's type [ISO/IEC 9075-14:2006 draft §20.15]. Corrected:
    // the draft selects USER_DEFINED_TYPE_CATALOG, _SCHEMA and _NAME, which
    // METHOD_SPECIFICATIONS shows as UDT_CATALOG, UDT_SCHEMA and UDT_NAME
    // [§5.34], and grants SELECT on METHOS_SPECS.
    SystemView {
        name: "METHOD_SPECS",
        query: r"SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
           UDT_CATALOG, UDT_SCHEMA, UDT_NAME,
           METHOD_NAME, IS_STATIC, IS_OVERRIDING,
           IS_CONSTRUCTOR, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH AS CHAR_MAX_LENGTH,
           CHARACTER_OCTET_LENGTH AS CHAR_OCTET_LENGTH,
           CHARACTER_SET_CATALOG AS CHAR_SET_CATALOG,
           CHARACTER_SET_SCHEMA AS CHAR_SET_SCHEMA,
           CHARACTER_SET_NAME, COLLATION_CATALOG, COLLATION_SCHEMA,
           COLLATION_NAME, NUMERIC_PRECISION, NUMERIC_PRECISION_RADIX AS NUMERIC_PREC_RADIX,
           NUMERIC_SCALE, DATETIME_PRECISION,
           RETURN_UDT_CATALOG, RETURN_UDT_SCHEMA,
           RETURN_UDT_NAME, SCOPE_CATALOG, SCOPE_SCHEMA,
           SCOPE_NAME, MAXIMUM_CARDINALITY AS MAX_CARDINALITY, DTD_IDENTIFIER,
           METHOD_LANGUAGE, PARAMETER_STYLE, IS_DETERMINISTIC,
           SQL_DATA_ACCESS, IS_NULL_CALL, TO_SQL_SPECIFIC_CATALOG AS TO_SQL_SPEC_CAT,
           TO_SQL_SPECIFIC_SCHEMA AS TO_SQL_SPEC_SCHEMA,
           TO_SQL_SPECIFIC_NAME AS TO_SQL_SPEC_NAME, AS_LOCATOR,
           XML_PRIMARY_MODIFIER AS XML_PRIMARY_MOD,
           XML_SECONDARY_MODIFIER AS XML_SECONDARY_MOD, XML_SCHEMA_CATALOG,
           XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME,
           XML_SCHEMA_NAMESPACE AS XML_SCHEMA_NSPACE, XML_SCHEMA_ELEMENT
    FROM INFORMATION_SCHEMA.METHOD_SPECIFICATIONS",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] METHOD_SPEC_PARAMS; with the XML
    // columns [ISO/IEC 9075-14:2006 draft §20.15].
    SystemView {
        name: "METHOD_SPEC_PARAMS",
        query: r"SELECT SPECIFIC_CATALOG, SPECIFIC_SCHEMA, SPECIFIC_NAME,
           ORDINAL_POSITION, PARAMETER_MODE, IS_RESULT,
           AS_LOCATOR, PARAMETER_NAME, FROM_SQL_SPECIFIC_CATALOG AS FROM_SQL_SPEC_CAT,
           FROM_SQL_SPECIFIC_SCHEMA AS FROM_SQL_SPEC_SCH,
           FROM_SQL_SPECIFIC_NAME AS FROM_SQL_SPEC_NAME, DATA_TYPE,
           CHARACTER_MAXIMUM_LENGTH AS CHAR_MAX_LENGTH,
           CHARACTER_OCTET_LENGTH AS CHAR_OCTET_LENGTH,
           CHARACTER_SET_CATALOG AS CHAR_SET_CATALOG,
           CHARACTER_SET_SCHEMA AS CHAR_SET_SCHEMA, CHARACTER_SET_NAME, COLLATION_CATALOG,
           COLLATION_SCHEMA, COLLATION_NAME, NUMERIC_PRECISION,
           NUMERIC_PRECISION_RADIX AS NUMERIC_PREC_RADIX, NUMERIC_SCALE, DATETIME_PRECISION,
           PARAMETER_UDT_CATALOG AS PARM_UDT_CATALOG,
           PARAMETER_UDT_SCHEMA AS PARM_UDT_SCHEMA,
           PARAMETER_UDT_NAME AS PARM_UDT_NAME, SCOPE_CATALOG,
           SCOPE_SCHEMA, SCOPE_NAME, MAXIMUM_CARDINALITY AS MAX_CARDINALITY,
           DTD_IDENTIFIER,
           XML_PRIMARY_MODIFIER AS XML_PRIMARY_MOD,
           XML_SECONDARY_MODIFIER AS XML_SECONDARY_MOD, XML_SCHEMA_CATALOG,
           XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME,
           XML_SCHEMA_NAMESPACE AS XML_SCHEMA_NSPACE, XML_SCHEMA_ELEMENT
    FROM INFORMATION_SCHEMA.METHOD_SPECIFICATION_PARAMETERS",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] REFERENCED_TYPES_S.
    SystemView {
        name: "REFERENCED_TYPES_S",
        query: r"SELECT OBJECT_CATALOG, OBJECT_SCHEMA, OBJECT_NAME,
           OBJECT_TYPE, REFERENCE_TYPE_IDENTIFIER AS REFERENCE_TYPE_ID, DATA_TYPE,
           CHARACTER_MAXIMUM_LENGTH AS CHAR_MAX_LENGTH,
           CHARACTER_OCTET_LENGTH AS CHAR_OCTET_LENGTH,
           CHARACTER_SET_CATALOG AS CHAR_SET_CATALOG,
           CHARACTER_SET_SCHEMA AS CHAR_SET_SCHEMA, CHARACTER_SET_NAME, COLLATION_CATALOG,
           COLLATION_SCHEMA, COLLATION_NAME, NUMERIC_PRECISION,
           NUMERIC_PRECISION_RADIX AS NUMERIC_PREC_RADIX, NUMERIC_SCALE, DATETIME_PRECISION,
           UDT_CATALOG, UDT_SCHEMA, UDT_NAME, SCOPE_CATALOG,
           SCOPE_SCHEMA, SCOPE_NAME, MAXIMUM_CARDINALITY AS MAX_CARDINALITY,
           DTD_IDENTIFIER
    FROM INFORMATION_SCHEMA.REFERENCED_TYPES",
    },
    // [ISO/IEC 9075-11:2006 draft §5.77] TABLE_METHOD_PRIVS.
    SystemView {
        name: "TABLE_METHOD_PRIVS",
        query: r"SELECT GRANTOR, GRANTEE, TABLE_CATALOG,
           TABLE_SCHEMA, TABLE_NAME, SPECIFIC_CATALOG,
           SPECIFIC_SCHEMA, SPECIFIC_NAME, IS_GRANTABLE
    FROM INFORMATION_SCHEMA.TABLE_METHOD_PRIVILEGES",
    },
];
