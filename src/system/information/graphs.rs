//! \[EXTENSION\] The views of the Information Schema of property graphs
//! (RULES.md D106, §20 of the property graph implementation
//! standard), each over its table of the Definition Schema
//! (`definition/graphs.rs`): PROPERTY_GRAPHS, each graph the current user
//! or an enabled role holds SELECT on, its definition shown to the owner
//! of its schema alone, as VIEWS shows a view's [ISO/IEC 9075:1992
//! §21.2.7]; PG_ELEMENT_TABLES, PG_LABELS, PG_PROPERTIES, PG_KEY_COLUMNS
//! and PG_EDGE_ENDPOINTS, the parts of those graphs; and
//! PROPERTY_GRAPH_PRIVILEGES, each SELECT on a graph granted to or by
//! them, as TABLE_PRIVILEGES shows a table's [§21.2.10]; and
//! GRAPH_STATISTICS, the statistics of those graphs (RULES.md D117,
//! `definition/graph_statistics.rs`).

use super::SystemView;

/// The views of property graphs, after those of modules.
pub(super) const VIEWS: &[SystemView] = &[
    // PG_EDGE_ENDPOINTS.
    SystemView {
        name: "PG_EDGE_ENDPOINTS",
        query: r"SELECT PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME,
            EDGE_TABLE_ALIAS, EDGE_END, VERTEX_TABLE_ALIAS, ORDINAL_POSITION,
            EDGE_COLUMN_NAME, VERTEX_COLUMN_NAME
     FROM DEFINITION_SCHEMA.PG_EDGE_ENDPOINTS
     WHERE ( PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME ) IN
             ( SELECT GP.PROPERTY_GRAPH_CATALOG, GP.PROPERTY_GRAPH_SCHEMA, GP.PROPERTY_GRAPH_NAME
               FROM DEFINITION_SCHEMA.PROPERTY_GRAPH_PRIVILEGES AS GP
               WHERE ( GP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                    OR GP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND PROPERTY_GRAPH_CATALOG = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // GRAPH_STATISTICS.
    SystemView {
        name: "GRAPH_STATISTICS",
        query: r"SELECT PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME,
            STATISTIC_KIND, ELEMENT_TABLE_ALIAS, PROPERTY_NAME,
            SOURCE_LABEL, EDGE_LABEL, DESTINATION_LABEL,
            ROW_COUNT, DISTINCT_VALUES, NULL_FRACTION,
            OUT_DEGREE_AVERAGE, OUT_DEGREE_MEDIAN, OUT_DEGREE_P90, OUT_DEGREE_P99, OUT_DEGREE_MAXIMUM,
            IN_DEGREE_AVERAGE, IN_DEGREE_MEDIAN, IN_DEGREE_P90, IN_DEGREE_P99, IN_DEGREE_MAXIMUM
     FROM DEFINITION_SCHEMA.GRAPH_STATISTICS
     WHERE ( PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME ) IN
             ( SELECT GP.PROPERTY_GRAPH_CATALOG, GP.PROPERTY_GRAPH_SCHEMA, GP.PROPERTY_GRAPH_NAME
               FROM DEFINITION_SCHEMA.PROPERTY_GRAPH_PRIVILEGES AS GP
               WHERE ( GP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                    OR GP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND PROPERTY_GRAPH_CATALOG = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // PG_ELEMENT_TABLES.
    SystemView {
        name: "PG_ELEMENT_TABLES",
        query: r"SELECT PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME,
            ELEMENT_TABLE_ALIAS, ELEMENT_TABLE_KIND,
            TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION, IS_UNDIRECTED, ELEMENT_TABLE_QUERY
     FROM DEFINITION_SCHEMA.PG_ELEMENT_TABLES
     WHERE ( PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME ) IN
             ( SELECT GP.PROPERTY_GRAPH_CATALOG, GP.PROPERTY_GRAPH_SCHEMA, GP.PROPERTY_GRAPH_NAME
               FROM DEFINITION_SCHEMA.PROPERTY_GRAPH_PRIVILEGES AS GP
               WHERE ( GP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                    OR GP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND PROPERTY_GRAPH_CATALOG = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // PG_KEY_COLUMNS.
    SystemView {
        name: "PG_KEY_COLUMNS",
        query: r"SELECT PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME,
            ELEMENT_TABLE_ALIAS, COLUMN_NAME, ORDINAL_POSITION
     FROM DEFINITION_SCHEMA.PG_KEY_COLUMNS
     WHERE ( PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME ) IN
             ( SELECT GP.PROPERTY_GRAPH_CATALOG, GP.PROPERTY_GRAPH_SCHEMA, GP.PROPERTY_GRAPH_NAME
               FROM DEFINITION_SCHEMA.PROPERTY_GRAPH_PRIVILEGES AS GP
               WHERE ( GP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                    OR GP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND PROPERTY_GRAPH_CATALOG = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // PG_LABELS.
    SystemView {
        name: "PG_LABELS",
        query: r"SELECT PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME,
            ELEMENT_TABLE_ALIAS, LABEL_NAME, ORDINAL_POSITION
     FROM DEFINITION_SCHEMA.PG_LABELS
     WHERE ( PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME ) IN
             ( SELECT GP.PROPERTY_GRAPH_CATALOG, GP.PROPERTY_GRAPH_SCHEMA, GP.PROPERTY_GRAPH_NAME
               FROM DEFINITION_SCHEMA.PROPERTY_GRAPH_PRIVILEGES AS GP
               WHERE ( GP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                    OR GP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND PROPERTY_GRAPH_CATALOG = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // PG_PROPERTIES.
    SystemView {
        name: "PG_PROPERTIES",
        query: r"SELECT PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME,
            ELEMENT_TABLE_ALIAS, LABEL_NAME, PROPERTY_NAME, ORDINAL_POSITION,
            PROPERTY_EXPRESSION, DATA_TYPE
     FROM DEFINITION_SCHEMA.PG_PROPERTIES
     WHERE ( PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME ) IN
             ( SELECT GP.PROPERTY_GRAPH_CATALOG, GP.PROPERTY_GRAPH_SCHEMA, GP.PROPERTY_GRAPH_NAME
               FROM DEFINITION_SCHEMA.PROPERTY_GRAPH_PRIVILEGES AS GP
               WHERE ( GP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                    OR GP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND PROPERTY_GRAPH_CATALOG = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // PROPERTY_GRAPH_PRIVILEGES.
    SystemView {
        name: "PROPERTY_GRAPH_PRIVILEGES",
        query: r"SELECT
       GRANTOR, GRANTEE, PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME,
       PRIVILEGE_TYPE, IS_GRANTABLE
     FROM DEFINITION_SCHEMA.PROPERTY_GRAPH_PRIVILEGES
     WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
          OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES )
          OR GRANTOR = CURRENT_USER
          OR GRANTOR IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
       AND PROPERTY_GRAPH_CATALOG = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // PROPERTY_GRAPHS.
    SystemView {
        name: "PROPERTY_GRAPHS",
        query: r"SELECT PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME,
            PROPERTY_GRAPH_MODE, IS_INVOKER_RIGHTS, IS_VALID,
            CASE WHEN ( PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA )
                        IN ( SELECT CATALOG_NAME, SCHEMA_NAME
                             FROM DEFINITION_SCHEMA.SCHEMATA
                             WHERE ( SCHEMA_OWNER = CURRENT_USER
                                  OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
                 THEN PROPERTY_GRAPH_DEFINITION
                 ELSE NULL
            END AS PROPERTY_GRAPH_DEFINITION
     FROM DEFINITION_SCHEMA.PROPERTY_GRAPHS
     WHERE ( PROPERTY_GRAPH_CATALOG, PROPERTY_GRAPH_SCHEMA, PROPERTY_GRAPH_NAME ) IN
             ( SELECT GP.PROPERTY_GRAPH_CATALOG, GP.PROPERTY_GRAPH_SCHEMA, GP.PROPERTY_GRAPH_NAME
               FROM DEFINITION_SCHEMA.PROPERTY_GRAPH_PRIVILEGES AS GP
               WHERE ( GP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                    OR GP.GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
       AND PROPERTY_GRAPH_CATALOG = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
];
