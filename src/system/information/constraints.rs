//! The views of the Information Schema of ISO/IEC 9075:1992 that describe
//! constraints, character sets, collations, translations and the usage of
//! tables, columns and domains, and SQL_LANGUAGES [§21.2.13 to §21.2.26],
//! as the standard defines them, with SEQUENCES among them, and the
//! columns ISO/IEC 9075-11:2006 draft Clause 5 adds to each, each noted at
//! its view.

use super::SystemView;

/// The views, in the standard's order.
pub(super) const VIEWS: &[SystemView] = &[
    // [ISO/IEC 9075:1992 §21.2.13] TABLE_CONSTRAINTS, and [EXTENSION]
    // NULLS_DISTINCT.
    SystemView {
        name: "TABLE_CONSTRAINTS",
        query: r"SELECT
         CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME,
         TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
         CONSTRAINT_TYPE, IS_DEFERRABLE, INITIALLY_DEFERRED, NULLS_DISTINCT
       FROM DEFINITION_SCHEMA.TABLE_CONSTRAINTS
            JOIN
            DEFINITION_SCHEMA.SCHEMATA S
            ON
             ( ( CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA )
             = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
          WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CONSTRAINT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.14] REFERENTIAL_CONSTRAINTS.
    SystemView {
        name: "REFERENTIAL_CONSTRAINTS",
        query: r"SELECT
         CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME,
         UNIQUE_CONSTRAINT_CATALOG, UNIQUE_CONSTRAINT_SCHEMA, UNIQUE_CONSTRAINT_NAME,
         MATCH_OPTION, UPDATE_RULE, DELETE_RULE
       FROM DEFINITION_SCHEMA.REFERENTIAL_CONSTRAINTS
            JOIN
            DEFINITION_SCHEMA.SCHEMATA S
            ON
             ( ( CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA )
             = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
          WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CONSTRAINT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.15] CHECK_CONSTRAINTS.
    SystemView {
        name: "CHECK_CONSTRAINTS",
        query: r"SELECT
         CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME, CHECK_CLAUSE
       FROM DEFINITION_SCHEMA.CHECK_CONSTRAINTS
            JOIN
            DEFINITION_SCHEMA.SCHEMATA S
            ON
             ( ( CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA )
             = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
          WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CONSTRAINT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.16] KEY_COLUMN_USAGE; with
    // POSITION_IN_UNIQUE_CONSTRAINT, as ISO/IEC 9075-11:2006 draft §5.32
    // adds it.
    SystemView {
        name: "KEY_COLUMN_USAGE",
        query: r"SELECT
         CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME,
         TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, ORDINAL_POSITION,
         POSITION_IN_UNIQUE_CONSTRAINT
       FROM DEFINITION_SCHEMA.KEY_COLUMN_USAGE
            JOIN
            DEFINITION_SCHEMA.SCHEMATA S
            ON
             ( ( CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA )
             = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
          WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CONSTRAINT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.17] ASSERTIONS.
    SystemView {
        name: "ASSERTIONS",
        query: r"SELECT
         CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME,
         IS_DEFERRABLE, INITIALLY_DEFERRED
       FROM DEFINITION_SCHEMA.ASSERTIONS
            JOIN
            DEFINITION_SCHEMA.SCHEMATA S
            ON
             ( ( CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA )
             = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
          WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CONSTRAINT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.18] CHARACTER_SETS; with
    // CHARACTER_REPERTOIRE, as ISO/IEC 9075-11:2006 draft §5.12 adds it.
    SystemView {
        name: "CHARACTER_SETS",
        query: r"SELECT
       CHARACTER_SET_CATALOG, CHARACTER_SET_SCHEMA, CHARACTER_SET_NAME,
       CHARACTER_REPERTOIRE, FORM_OF_USE, NUMBER_OF_CHARACTERS,
       DEFAULT_COLLATE_CATALOG, DEFAULT_COLLATE_SCHEMA, DEFAULT_COLLATE_NAME
     FROM DEFINITION_SCHEMA.CHARACTER_SETS
     WHERE ( CHARACTER_SET_CATALOG, CHARACTER_SET_SCHEMA, CHARACTER_SET_NAME, 'CHARACTER SET')
             IN
             ( SELECT OBJECT_CATALOG, OBJECT_SCHEMA, OBJECT_NAME, OBJECT_TYPE
                 FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES
                 WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                         OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND CHARACTER_SET_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.19] COLLATIONS.
    SystemView {
        name: "COLLATIONS",
        query: r"SELECT
       COLLATION_CATALOG, COLLATION_SCHEMA, COLLATION_NAME,
       CHARACTER_SET_CATALOG, CHARACTER_SET_SCHEMA, CHARACTER_SET_NAME,
       PAD_ATTRIBUTE
     FROM DEFINITION_SCHEMA.COLLATIONS
     WHERE ( COLLATION_CATALOG, COLLATION_SCHEMA, COLLATION_NAME, 'COLLATION')
             IN
             ( SELECT OBJECT_CATALOG, OBJECT_SCHEMA, OBJECT_NAME, OBJECT_TYPE
                 FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES
                 WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                         OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND COLLATION_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [EXTENSION] SEQUENCES: each sequence generator the current user, or
    // PUBLIC, holds USAGE on, as COLLATIONS shows collations.
    SystemView {
        name: "SEQUENCES",
        query: r"SELECT
       SEQUENCE_CATALOG, SEQUENCE_SCHEMA, SEQUENCE_NAME,
       DATA_TYPE, NUMERIC_PRECISION, NUMERIC_PRECISION_RADIX, NUMERIC_SCALE,
       START_VALUE, MINIMUM_VALUE, MAXIMUM_VALUE, INCREMENT, CYCLE_OPTION
     FROM DEFINITION_SCHEMA.SEQUENCES
     WHERE ( SEQUENCE_CATALOG, SEQUENCE_SCHEMA, SEQUENCE_NAME, 'SEQUENCE')
             IN
             ( SELECT OBJECT_CATALOG, OBJECT_SCHEMA, OBJECT_NAME, OBJECT_TYPE
                 FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES
                 WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                         OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND SEQUENCE_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.20] TRANSLATIONS; with the translation
    // source, as ISO/IEC 9075-11:2006 draft §5.63 adds it.
    SystemView {
        name: "TRANSLATIONS",
        query: r"SELECT
       TRANSLATION_CATALOG, TRANSLATION_SCHEMA, TRANSLATION_NAME,
       SOURCE_CHARACTER_SET_CATALOG, SOURCE_CHARACTER_SET_SCHEMA,
         SOURCE_CHARACTER_SET_NAME,
       TARGET_CHARACTER_SET_CATALOG, TARGET_CHARACTER_SET_SCHEMA,
         TARGET_CHARACTER_SET_NAME,
       TRANSLATION_SOURCE_CATALOG, TRANSLATION_SOURCE_SCHEMA,
         TRANSLATION_SOURCE_NAME
     FROM DEFINITION_SCHEMA.TRANSLATIONS
     WHERE ( TRANSLATION_CATALOG, TRANSLATION_SCHEMA, TRANSLATION_NAME, 'TRANSLATION')
             IN
             ( SELECT OBJECT_CATALOG, OBJECT_SCHEMA, OBJECT_NAME, OBJECT_TYPE
                 FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES
                 WHERE ( GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                         OR GRANTEE IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) ) )
         AND TRANSLATION_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.21] VIEW_TABLE_USAGE.
    SystemView {
        name: "VIEW_TABLE_USAGE",
        query: r"SELECT
       VIEW_CATALOG, VIEW_SCHEMA, VIEW_NAME,
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME
     FROM DEFINITION_SCHEMA.VIEW_TABLE_USAGE
          JOIN
          DEFINITION_SCHEMA.SCHEMATA S
         ON
           ( ( TABLE_CATALOG, TABLE_SCHEMA ) =
           ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
       WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND VIEW_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.22] VIEW_COLUMN_USAGE.
    SystemView {
        name: "VIEW_COLUMN_USAGE",
        query: r"SELECT VIEW_CATALOG, VIEW_SCHEMA, VIEW_NAME,
            TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME
       FROM DEFINITION_SCHEMA.VIEW_COLUMN_USAGE
         JOIN
         DEFINITION_SCHEMA.SCHEMATA S
           ON
           ( ( TABLE_CATALOG, TABLE_SCHEMA ) =
           ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
       WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND VIEW_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.23] CONSTRAINT_TABLE_USAGE; corrected: the derived table given the correlation name U, which §6.3 F requires.
    SystemView {
        name: "CONSTRAINT_TABLE_USAGE",
        query: r"SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
              CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME FROM
     (
       ( SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME,
                CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME
           FROM DEFINITION_SCHEMA.CHECK_COLUMN_USAGE )
     UNION
       ( SELECT PK.TABLE_CATALOG, PK.TABLE_SCHEMA, PK.TABLE_NAME,
                FK.CONSTRAINT_CATALOG, FK.CONSTRAINT_SCHEMA, FK.CONSTRAINT_NAME
           FROM
           DEFINITION_SCHEMA.REFERENTIAL_CONSTRAINTS AS FK
           JOIN
           DEFINITION_SCHEMA.TABLE_CONSTRAINTS AS PK
             ON
               ( FK.UNIQUE_CONSTRAINT_CATALOG, FK.UNIQUE_CONSTRAINT_SCHEMA,
                   FK.UNIQUE_CONSTRAINT_NAME )
             = ( PK.CONSTRAINT_CATALOG, PK.CONSTRAINT_SCHEMA, PK.CONSTRAINT_NAME )
       )
     ) AS U
     JOIN
       DEFINITION_SCHEMA.SCHEMATA S
          ON
           ( ( TABLE_CATALOG, TABLE_SCHEMA ) =
           ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
       WHERE ( S.SCHEMA_OWNER = CURRENT_USER OR S.SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CONSTRAINT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.24] CONSTRAINT_COLUMN_USAGE; corrected: the UNION put inside the derived table it is written beside, named U, as §6.3 F requires.
    SystemView {
        name: "CONSTRAINT_COLUMN_USAGE",
        query: r"SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME,
              CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME FROM
       ( ( SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME,
                CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME
           FROM DEFINITION_SCHEMA.CHECK_COLUMN_USAGE )
         UNION
         ( SELECT K.TABLE_CATALOG, K.TABLE_SCHEMA, K.TABLE_NAME, K.COLUMN_NAME,
                  CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME
             FROM DEFINITION_SCHEMA.TABLE_CONSTRAINTS
           JOIN DEFINITION_SCHEMA.KEY_COLUMN_USAGE AS K
             USING ( CONSTRAINT_CATALOG, CONSTRAINT_SCHEMA, CONSTRAINT_NAME )
       ) ) AS U
       JOIN
         DEFINITION_SCHEMA.SCHEMATA
          ON
           ( ( TABLE_CATALOG, TABLE_SCHEMA ) =
           ( CATALOG_NAME, SCHEMA_NAME ) )
         WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND CONSTRAINT_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.25] COLUMN_DOMAIN_USAGE.
    SystemView {
        name: "COLUMN_DOMAIN_USAGE",
        query: r"SELECT
       D.DOMAIN_CATALOG, D.DOMAIN_SCHEMA, D.DOMAIN_NAME,
       TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME
     FROM DEFINITION_SCHEMA.COLUMNS C
          JOIN
              DEFINITION_SCHEMA.DOMAINS D
              JOIN
              DEFINITION_SCHEMA.SCHEMATA S
                ON ( ( DOMAIN_CATALOG, DOMAIN_SCHEMA )
                = ( S.CATALOG_NAME, S.SCHEMA_NAME ) )
          ON ( ( D.DOMAIN_CATALOG, D.DOMAIN_SCHEMA, D.DOMAIN_NAME )
                = ( C.DOMAIN_CATALOG, C.DOMAIN_SCHEMA, C.DOMAIN_NAME ) )
       WHERE ( SCHEMA_OWNER = CURRENT_USER OR SCHEMA_OWNER IN ( SELECT ROLE_NAME FROM ENABLED_ROLES ) )
         AND C.DOMAIN_NAME IS NOT NULL
         AND D.DOMAIN_CATALOG
           = ( SELECT CATALOG_NAME FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075:1992 §21.2.26] SQL_LANGUAGES.
    SystemView {
        name: "SQL_LANGUAGES",
        query: r"SELECT
       SQL_LANGUAGE_SOURCE, SQL_LANGUAGE_YEAR, SQL_LANGUAGE_CONFORMANCE,
         SQL_LANGUAGE_INTEGRITY, SQL_LANGUAGE_IMPLEMENTATION,
         SQL_LANGUAGE_BINDING_STYLE, SQL_LANGUAGE_PROGRAMMING_LANGUAGE
     FROM DEFINITION_SCHEMA.SQL_LANGUAGES",
    },
];
