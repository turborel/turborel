//! [ISO/IEC 9075-14:2006 draft §20.12 to §20.14] The views of registered
//! XML Schemas: XML_SCHEMAS, XML_SCHEMA_NAMESPACES and
//! XML_SCHEMA_ELEMENTS, each showing the registered XML Schemas the
//! current user, PUBLIC or an enabled role holds USAGE on, over the
//! Definition Schema's tables of them (`definition/xml_schemas.rs`). The
//! text is the draft's, its `XSN. XML_SCHEMA_NAMESPACE_IS_DETERMINISTIC`
//! written without the space. Their short name views [§20.15] are
//! `short_names/xml_schemas.rs`'s.

use super::SystemView;

/// The views, in the draft's order.
pub(super) const VIEWS: &[SystemView] = &[
    // [ISO/IEC 9075-14:2006 draft §20.12] XML_SCHEMA_ELEMENTS.
    SystemView {
        name: "XML_SCHEMA_ELEMENTS",
        query: r"SELECT XS.XML_SCHEMA_TARGET_NAMESPACE, XS.XML_SCHEMA_LOCATION,
         XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME,
         XE.XML_SCHEMA_NAMESPACE, XE.XML_SCHEMA_ELEMENT,
         XE.XML_SCHEMA_ELEMENT_IS_DETERMINISTIC
  FROM DEFINITION_SCHEMA.XML_SCHEMA_ELEMENTS AS XE
  JOIN DEFINITION_SCHEMA.XML_SCHEMAS AS XS
  USING ( XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME )
  WHERE ( XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA,
          XML_SCHEMA_NAME, 'XML SCHEMA' )
       IN ( SELECT UP.OBJECT_CATALOG, UP.OBJECT_SCHEMA,
                    UP.OBJECT_NAME, UP.OBJECT_TYPE
            FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES AS UP
            WHERE ( UP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                 OR
                     UP.GRANTEE IN ( SELECT ROLE_NAME
                                     FROM ENABLED_ROLES ) ) )
    AND XML_SCHEMA_CATALOG =
        ( SELECT CATALOG_NAME
          FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075-14:2006 draft §20.13] XML_SCHEMA_NAMESPACES.
    SystemView {
        name: "XML_SCHEMA_NAMESPACES",
        query: r"SELECT XS.XML_SCHEMA_TARGET_NAMESPACE, XS.XML_SCHEMA_LOCATION,
           XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME,
           XSN.XML_SCHEMA_NAMESPACE,
           XSN.XML_SCHEMA_NAMESPACE_IS_DETERMINISTIC
    FROM DEFINITION_SCHEMA.XML_SCHEMA_NAMESPACES AS XSN
    JOIN DEFINITION_SCHEMA.XML_SCHEMAS AS XS
    USING ( XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME )
    WHERE ( XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA,
            XML_SCHEMA_NAME, 'XML SCHEMA' )
        IN ( SELECT UP.OBJECT_CATALOG, UP.OBJECT_SCHEMA,
                     UP.OBJECT_NAME, UP.OBJECT_TYPE
             FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES AS UP
             WHERE ( UP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
                  OR
                      UP.GRANTEE IN ( SELECT ROLE_NAME
                                      FROM ENABLED_ROLES ) ) )
      AND XML_SCHEMA_CATALOG =
          ( SELECT CATALOG_NAME
            FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
    // [ISO/IEC 9075-14:2006 draft §20.14] XML_SCHEMAS.
    SystemView {
        name: "XML_SCHEMAS",
        query: r"SELECT XML_SCHEMA_TARGET_NAMESPACE, XML_SCHEMA_LOCATION,
    XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA, XML_SCHEMA_NAME,
    XML_SCHEMA_IS_DETERMINISTIC, XML_SCHEMA_IS_PERMANENT
FROM DEFINITION_SCHEMA.XML_SCHEMAS
WHERE ( XML_SCHEMA_CATALOG, XML_SCHEMA_SCHEMA,
        XML_SCHEMA_NAME, 'XML SCHEMA' )
     IN ( SELECT UP.OBJECT_CATALOG, UP.OBJECT_SCHEMA,
                 UP.OBJECT_NAME, UP.OBJECT_TYPE
          FROM DEFINITION_SCHEMA.USAGE_PRIVILEGES AS UP
          WHERE ( UP.GRANTEE IN ( 'PUBLIC', CURRENT_USER )
       OR
          UP.GRANTEE IN ( SELECT ROLE_NAME
                           FROM ENABLED_ROLES ) ) )
   AND XML_SCHEMA_CATALOG =
       ( SELECT CATALOG_NAME
         FROM INFORMATION_SCHEMA_CATALOG_NAME )",
    },
];
