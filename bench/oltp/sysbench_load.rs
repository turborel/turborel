//! The sysbench-style tables, as the prepare command makes them: ten tables
//! `sbtest1` to `sbtest10`, `id` an identity column given its values by
//! default, each row's `k` drawn uniformly over the rows and `c` and `pad`
//! of random digits in groups; then the index on `k` of each.

use turborel::db::Session;
use turborel::value::Value;

use crate::random::Random;
use crate::sysbench::{C_TEMPLATE, PAD_TEMPLATE, TABLES};
use crate::tpcc_load::{Insert, int};

/// The seed of the load's draws.
const SEED: u64 = 1_140;

/// Creates and fills the tables of `rows` rows each.
pub fn load(s: &Session, rows: i64) {
    let r = &mut Random::new(SEED);
    for t in 1..=TABLES {
        s.run(&format!(
            "CREATE TABLE sbtest{t}(id INTEGER GENERATED BY DEFAULT AS IDENTITY, k INTEGER DEFAULT 0 NOT NULL, \
                c CHAR(120) DEFAULT '' NOT NULL, \"pad\" CHAR(60) DEFAULT '' NOT NULL, PRIMARY KEY (id))"
        ))
        .unwrap();
        s.commit().unwrap();
        {
            let mut insert = Insert::new(s, &format!("sbtest{t}"), "k, c, \"pad\"");
            for _ in 0..rows {
                let k = int(r.number(1, rows));
                insert.push(vec![k, Value::Char(r.template(C_TEMPLATE).into()), Value::Char(r.template(PAD_TEMPLATE).into())]);
            }
        }
        s.run(&format!("CREATE INDEX k_{t} ON sbtest{t}(k)")).unwrap();
        s.commit().unwrap();
    }
}
