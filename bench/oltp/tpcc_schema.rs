//! The TPROC-C-style schema, as the driver the workload follows creates
//! it: nine tables, each keyed but HISTORY, and two indexes, CUSTOMER's by
//! last name and ORDERS' by customer, made after the load.

/// The tables, in the order they are created.
pub const TABLES: [&str; 9] = [
    "CREATE TABLE WAREHOUSE (W_ID INTEGER NOT NULL, W_YTD DECIMAL(12,2), W_TAX DECIMAL(4,4), W_NAME VARCHAR(10), \
        W_STREET_1 VARCHAR(20), W_STREET_2 VARCHAR(20), W_CITY VARCHAR(20), W_STATE CHAR(2), W_ZIP CHAR(9), \
        CONSTRAINT WAREHOUSE_I1 PRIMARY KEY (W_ID))",
    "CREATE TABLE DISTRICT (D_W_ID INTEGER NOT NULL, D_ID SMALLINT NOT NULL, D_YTD DECIMAL(12,2), D_TAX DECIMAL(4,4), \
        D_NEXT_O_ID INTEGER, D_NAME VARCHAR(10), D_STREET_1 VARCHAR(20), D_STREET_2 VARCHAR(20), D_CITY VARCHAR(20), \
        D_STATE CHAR(2), D_ZIP CHAR(9), CONSTRAINT DISTRICT_I1 PRIMARY KEY (D_W_ID, D_ID))",
    "CREATE TABLE CUSTOMER (C_W_ID INTEGER NOT NULL, C_D_ID SMALLINT NOT NULL, C_ID INTEGER NOT NULL, \
        C_DISCOUNT DECIMAL(4,4), C_CREDIT CHAR(2), C_LAST VARCHAR(16), C_FIRST VARCHAR(16), C_CREDIT_LIM DECIMAL(12,2), \
        C_BALANCE DECIMAL(12,2), C_YTD_PAYMENT DECIMAL(12,2), C_PAYMENT_CNT SMALLINT, C_DELIVERY_CNT SMALLINT, \
        C_STREET_1 VARCHAR(20), C_STREET_2 VARCHAR(20), C_CITY VARCHAR(20), C_STATE CHAR(2), C_ZIP CHAR(9), \
        C_PHONE CHAR(16), C_SINCE TIMESTAMP(0), C_MIDDLE CHAR(2), C_DATA VARCHAR(500), \
        CONSTRAINT CUSTOMER_I1 PRIMARY KEY (C_W_ID, C_D_ID, C_ID))",
    "CREATE TABLE HISTORY (H_C_ID INTEGER, H_C_D_ID SMALLINT, H_C_W_ID INTEGER, H_D_ID SMALLINT, H_W_ID INTEGER, \
        H_DATE TIMESTAMP(0), H_AMOUNT DECIMAL(6,2), H_DATA VARCHAR(24))",
    "CREATE TABLE NEW_ORDER (NO_W_ID INTEGER NOT NULL, NO_D_ID SMALLINT NOT NULL, NO_O_ID INTEGER NOT NULL, \
        CONSTRAINT NEW_ORDER_I1 PRIMARY KEY (NO_W_ID, NO_D_ID, NO_O_ID))",
    "CREATE TABLE ORDERS (O_W_ID INTEGER NOT NULL, O_D_ID SMALLINT NOT NULL, O_ID INTEGER NOT NULL, O_C_ID INTEGER, \
        O_CARRIER_ID SMALLINT, O_OL_CNT SMALLINT, O_ALL_LOCAL SMALLINT, O_ENTRY_D TIMESTAMP(0), \
        CONSTRAINT ORDERS_I1 PRIMARY KEY (O_W_ID, O_D_ID, O_ID))",
    "CREATE TABLE ORDER_LINE (OL_W_ID INTEGER NOT NULL, OL_D_ID SMALLINT NOT NULL, OL_O_ID INTEGER NOT NULL, \
        OL_NUMBER SMALLINT NOT NULL, OL_I_ID INTEGER, OL_DELIVERY_D TIMESTAMP(0), OL_AMOUNT DECIMAL(6,2), \
        OL_SUPPLY_W_ID INTEGER, OL_QUANTITY SMALLINT, OL_DIST_INFO CHAR(24), \
        CONSTRAINT ORDER_LINE_I1 PRIMARY KEY (OL_W_ID, OL_D_ID, OL_O_ID, OL_NUMBER))",
    "CREATE TABLE ITEM (I_ID INTEGER NOT NULL, I_IM_ID INTEGER, I_NAME VARCHAR(24), I_PRICE DECIMAL(5,2), \
        I_DATA VARCHAR(50), CONSTRAINT ITEM_I1 PRIMARY KEY (I_ID))",
    "CREATE TABLE STOCK (S_W_ID INTEGER NOT NULL, S_I_ID INTEGER NOT NULL, S_QUANTITY SMALLINT, S_DIST_01 CHAR(24), \
        S_DIST_02 CHAR(24), S_DIST_03 CHAR(24), S_DIST_04 CHAR(24), S_DIST_05 CHAR(24), S_DIST_06 CHAR(24), \
        S_DIST_07 CHAR(24), S_DIST_08 CHAR(24), S_DIST_09 CHAR(24), S_DIST_10 CHAR(24), S_YTD INTEGER, \
        S_ORDER_CNT SMALLINT, S_REMOTE_CNT SMALLINT, S_DATA VARCHAR(50), CONSTRAINT STOCK_I1 PRIMARY KEY (S_W_ID, \
        S_I_ID))",
];

/// The indexes made after the load.
pub const INDEXES: [&str; 2] = [
    "CREATE INDEX CUSTOMER_I2 ON CUSTOMER (C_W_ID, C_D_ID, C_LAST, C_FIRST, C_ID)",
    "CREATE INDEX ORDERS_I2 ON ORDERS (O_W_ID, O_D_ID, O_C_ID, O_ID)",
];
